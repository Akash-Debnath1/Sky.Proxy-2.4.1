#!/usr/bin/env node
/**
 * tools/gen-tz.mjs — ГЕНЕРАТОР ФАЙЛОВ ЧАСОВЫХ ПОЯСОВ (2.2).
 *
 * Запуск:  node tools/gen-tz.mjs
 *
 * Что делает. Берёт список зон из метаданных moment-timezone (источник —
 * тот же, из которого когда-то собран src/shared/tz-country.js), пишет:
 *   src/tz/zones/<Area__City>.js  — по файлу на зону, каждый кладёт имя
 *                                   пояса в self.__PXS_TZ;
 *   src/shared/tz-country.js      — таблицу «страна → первый пояс страны»
 *                                   для запасного пути, когда геосервис
 *                                   пояс не вернул.
 *
 * Почему файлы, а не один список. Подмена ставится через
 * chrome.scripting.registerContentScripts: браузер сам вкладывает файлы в
 * страницу на document_start, до её скриптов. Для этого имя пояса должно
 * быть кодом конкретного файла — выбирает его фон (src/background/tz.js)
 * по IP активного прокси. Один файл со всеми 400 зонами тянул бы в
 * каждую вкладку лишние сотни килобайт.
 *
 * Почему метаданные качаются. Список зон меняется с выходом базы IANA;
 * cked в репозитории список устарел бы молча. Скрипт запускают руками,
 * когда нужно обновить, — не при сборке расширения.
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ZONES_DIR = path.join(ROOT, 'src/tz/zones');
const COUNTRY_FILE = path.join(ROOT, 'src/shared/tz-country.js');
/*
 * Адреса по порядку: первый — обычный источник moment-timezone (на
 * момент 2.2 отдавал 404), второй и третий — тот же файл из репозитория
 * и с CDN. Проверка полей ниже одна на всех: формат мог смениться.
 */
const META_URLS = Object.freeze([
  'https://momentjs.com/downloads/meta/latest.json',
  'https://raw.githubusercontent.com/moment/moment-timezone/develop/data/meta/latest.json',
  'https://cdn.jsdelivr.net/npm/moment-timezone/data/meta/latest.json',
]);

/*
 * Страны с несколькими поясами: запасной путь должен вести в «обычный»
 * пояс страны, а не в крайний. Алфавитный порядок дал бы США — Адак
 * (Гавайи), Россию — Калининград, Бразилию — Фернанду-ди-Норонья. Здесь
 * перечислены пояса, которые страна сама считает основными (столица и
 * крупнейшие города). Список короткий намеренно: он нужен только там,
 * где «первый по алфавиту» заметно врёт.
 */
const PRIMARY_ZONE = Object.freeze({
  US: 'America/New_York',
  RU: 'Europe/Moscow',
  CA: 'America/Toronto',
  AU: 'Australia/Sydney',
  BR: 'America/Sao_Paulo',
  CN: 'Asia/Shanghai',
  MX: 'America/Mexico_City',
  ID: 'Asia/Jakarta',
  AR: 'America/Argentina/Buenos_Aires',
  CL: 'America/Santiago',
  KZ: 'Asia/Almaty',
  EC: 'America/Guayaquil',
  ES: 'Europe/Madrid',
  PT: 'Europe/Lisbon',
  UA: 'Europe/Kyiv',
  NZ: 'Pacific/Auckland',
  ZA: 'Africa/Johannesburg',
  IN: 'Asia/Kolkata',
  BD: 'Asia/Dhaka',
  PK: 'Asia/Karachi',
});

/** «America/Argentina/Buenos_Aires» → «America__Argentina__Buenos_Aires». */
const slug = (zone) => zone.replace(/\//g, '__');

/** Русская форма числа файлов — только для сообщения в консоли. */
const nFiles = (n) => `${n} ${n % 10 === 1 && n % 100 !== 11 ? 'файл' : n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14) ? 'файла' : 'файлов'}`;

async function fetchMeta() {
  const failures = [];
  for (const url of META_URLS) {
    try {
      const res = await fetch(url, { cache: 'no-store' });
      if (!res.ok) { failures.push(`${url}: HTTP ${res.status}`); continue; }
      const meta = await res.json();
      /* В нынешнем файле zones — объект «имя зоны → сведения», в старом
         был массив имён; принимаем оба. */
      const zones = Array.isArray(meta && meta.zones)
        ? meta.zones
        : meta && meta.zones && typeof meta.zones === 'object' ? Object.keys(meta.zones) : [];
      if (!meta || !zones.length || !meta.countries || typeof meta.countries !== 'object') {
        failures.push(`${url}: нет полей zones/countries`);
        continue;
      }
      meta.zoneList = zones;
      console.log(`[gen-tz] источник: ${url}`);
      return meta;
    } catch (err) {
      failures.push(`${url}: ${err.message}`);
    }
  }
  throw new Error(`метаданные не скачались:\n  ${failures.join('\n  ')}`);
}

async function writeZones(zones) {
  await fs.mkdir(ZONES_DIR, { recursive: true });
  const keep = new Set(zones.map((z) => `${slug(z)}.js`));
  for (const zone of zones) {
    const body = `/* generated by tools/gen-tz.mjs — IANA zone for the MAIN-world patch */\n`
      + `self.__PXS_TZ=${JSON.stringify(zone)};\n`;
    await fs.writeFile(path.join(ZONES_DIR, `${slug(zone)}.js`), body, 'utf8');
  }
  /* Удаляем файлы зон, которых больше нет в базе: иначе папка копит
     мусор, а фон может выбрать пояс по старым метаданным страны. */
  const have = await fs.readdir(ZONES_DIR).catch(() => []);
  let removed = 0;
  for (const name of have) {
    if (!name.endsWith('.js') || keep.has(name)) continue;
    await fs.unlink(path.join(ZONES_DIR, name));
    removed += 1;
  }
  return removed;
}

async function writeCountries(meta) {
  /* Первая зона страны в порядке z. Now moment-timezone перечисляет
     зоны с сортировкой по смещению; нам нужен стабильный выбор, поэтому
     сортируем имена сами и берём первое — результат один и тот же от
     запуска к запуску. */
  /* В этом файле метаданных countries — «код страны → {zones: [...]}»;
     если формат когда-нибудь станет «зона → код» (как в старом файле),
     второй проход разберёт и его. */
  const byCountry = new Map();
  for (const [cc, info] of Object.entries(meta.countries)) {
    const list = Array.isArray(info) ? info : info && Array.isArray(info.zones) ? info.zones : [];
    for (const zone of list) {
      if (typeof zone !== 'string' || !zone) continue;
      const have = byCountry.get(cc) || [];
      have.push(zone);
      byCountry.set(cc, have);
    }
  }
  if (!byCountry.size) {
    for (const zone of meta.zones) {
      const cc = meta.countries[zone];
      if (typeof cc !== 'string') continue;
      const have = byCountry.get(cc) || [];
      have.push(zone);
      byCountry.set(cc, have);
    }
  }
  const entries = [...byCountry.keys()].sort().map((cc) => {
    const list = byCountry.get(cc);
    const own = PRIMARY_ZONE[cc];
    /* Свой пояс страны — только если он в её списке: таблица стран
       могла устареть, а выдумывать зону нельзя. */
    const zone = own && list.includes(own) ? own : list.slice().sort()[0];
    return `  ${cc}: ${JSON.stringify(zone)},`;
  });
  const body = `/**
 * src/shared/tz-country.js — СТРАНА → ЧАСОВОЙ ПОЯС (2.2).
 *
 * ЗАПАСНОЙ ПУТЬ. Основной источник пояса — геосервис по IP (см.
 * src/background/tz.js). Если он не ответил, берём страну записи прокси
 * (cc) и первый пояс этой страны из таблицы ниже. У больших стран
 * поясов несколько, и таблица может ошибиться на час-два — это лучше,
 * чем ничего, но хуже ответа геосервиса.
 *
 * ФАЙЛ СГЕНЕРИРОВАН: node tools/gen-tz.mjs. Руками не править —
 * перезапуск скрипта перепишет файл. Источник — метаданные
 * moment-timezone (${meta.version || 'версия неизвестна'}), база IANA.
 */

/** @type {Readonly<Record<string, string>>} */
export const COUNTRY_TZ = Object.freeze({
${entries.join('\n')}
});
`;
  await fs.writeFile(COUNTRY_FILE, body, 'utf8');
  return entries.length;
}

async function main() {
  const meta = await fetchMeta();
  const zones = [...new Set(meta.zoneList)].sort();
  const removed = await writeZones(zones);
  const countries = await writeCountries(meta);
  console.log(`[gen-tz] зон: ${nFiles(zones.length)}, стран: ${countries}`
    + (removed ? `, убрано устаревших файлов: ${removed}` : ''));
  if (meta.version) console.log(`[gen-tz] база: ${meta.version}`);
}

main().catch((err) => {
  console.error('[gen-tz] ошибка:', err.message);
  process.exit(1);
});
