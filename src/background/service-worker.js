/* ── блокировка WebRTC (7А) ───────────────────────────────────────────
 * Пока прокси включён, сайт может узнать настоящий IP через WebRTC мимо
 * прокси: его служебные запросы идут по UDP напрямую. Закрывает утечку
 * политика браузера webRTCIPHandlingPolicy = 'disable_non_proxied_udp'
 * (WebRTC запрещён любой UDP не через прокси). Ставить её может только
 * расширение с разрешением privacy, а оно опциональное: запрашивает
 * страница из клика по тумблеру (окно Chrome показывается только по
 * действию человека), фон лишь проверяет, есть ли оно.
 *
 * Правило одно: политика стоит ровно тогда, когда settings.webrtc,
 * state.enabled и разрешение есть; иначе снимается — чтобы звонки и
 * видео без прокси работали. Прежних значений в памяти воркера нет (сон
 * стирает), поэтому applyWebrtc всякий раз читает, что стоит у браузера,
 * и меняет только при расхождении — лишний вызов молчит. Зовётся при
 * старте после сверки, при каждом изменении state и settings и при
 * получении разрешения (chrome.permissions.onAdded): если настройка уже
 * включена (у всех после обновления — включена по умолчанию), страница
 * при удачном запросе ничего не запишет — значение то же, — и без этого
 * события фон о разрешении не узнал бы.
 *
 * Не через очередь применений inLine: это не настройка прокси. Своя
 * очередь webrtcLine — включение прокси даёт две записи состояния за
 * миллисекунды (enabled, затем levelOfControl), и два вызова внахлёст
 * ставили бы политику дважды. Память воркера — допустимо (решение
 * человека 10.09, В3, исключение по 3.2): в ней только работа в полёте,
 * после сна пустая.
 *
 * Уровни управления те же четыре, что у прокси (3.11):
 * controlled_by_other_extensions и not_controllable — не ставить, строка
 * в консоль; в диагностику не пишется (поля нет). При удалении расширения
 * политику снимает браузер сам. При отзыве разрешения снять её нельзя —
 * chrome.privacy без разрешения недоступен; снимает ли её браузер сам —
 * известное ограничение, не чинится (решение человека 10.09).
 */
const WEBRTC_POLICY = 'disable_non_proxied_udp';
const PRIVACY = { permissions: ['privacy'] };

let webrtcLine = Promise.resolve();

/**
 * Привести политику WebRTC к правилу. Ошибок наружу не бросает — пишет
 * в консоль: ни старт, ни подписка от неё зависеть не должны.
 *
 * @param {string} reason 'start' | 'state' | 'settings' | 'permission'
 * @returns {Promise<void>}
 */
function applyWebrtc(reason) {
  const turn = webrtcLine.then(() => runApplyWebrtc(reason));
  webrtcLine = turn.catch(() => {});
  return turn.catch((err) => {
    console.error(`[pxs] WebRTC (${reason}): политика не применена —`, err);
  });
}

async function runApplyWebrtc(reason) {
  const granted = await chrome.permissions.contains(PRIVACY);
  if (!granted) return;   // без разрешения политику ни поставить, ни снять — делать нечего

  const policy = chrome.privacy && chrome.privacy.network && chrome.privacy.network.webRTCIPHandlingPolicy;
  if (!policy) {
    console.warn(`[pxs] WebRTC (${reason}): разрешение есть, а chrome.privacy недоступен — политика не тронута`);
    return;
  }

  const [settings, st] = await Promise.all([state.getSettings(), state.getState()]);
  const want = settings.webrtc === true && st.enabled === true;
  const cur = await policy.get({});
  const level = cur && typeof cur.levelOfControl === 'string' ? cur.levelOfControl : 'not_controllable';

  if (want) {
    if (level === 'controlled_by_other_extensions') {
      console.log('[pxs] WebRTC: политикой управляет другое расширение');
      return;
    }
    if (level === 'not_controllable') {
      console.log('[pxs] WebRTC: управление политикой недоступно — политика организации или настройки запуска браузера');
      return;
    }
    if (level === 'controlled_by_this_extension' && cur.value === WEBRTC_POLICY) return;
    await policy.set({ value: WEBRTC_POLICY, scope: 'regular' });
    console.log(`[pxs] WebRTC (${reason}): политика ${WEBRTC_POLICY} поставлена — прокси включён, тумблер включён`);
    return;
  }

  if (level === 'controlled_by_this_extension') {
    await policy.clear({ scope: 'regular' });
    console.log(`[pxs] WebRTC (${reason}): политика снята — ${st.enabled ? 'тумблер выключен' : 'прокси выключен'}`);
    return;
  }
  if (level === 'controlled_by_other_extensions') {
    // Наша могла остаться под чужой (поставили раньше него) — снимаем молча, чтобы не всплыла при его удалении.
    await policy.clear({ scope: 'regular' });
  }
}

/*
 * Разрешение privacy (7А). Пришло — поставить политику, если она нужна
 * (см. выше: страница при уже включённой настройке не пишет ничего).
 * Ушло — записать webrtc: false: страница перерисует тумблер по подписке,
 * а строку «нужно разрешение» покажет сама, слушая то же событие (В1-а).
 * Слушатели на верхнем уровне, работа возвращается наружу.
 */
function hasPrivacy(p) {
  return !!(p && Array.isArray(p.permissions) && p.permissions.includes('privacy'));
}

chrome.permissions.onAdded.addListener((p) => {
  if (!hasPrivacy(p)) return undefined;
  console.log('[pxs] WebRTC: разрешение privacy получено');
  return applyWebrtc('permission');
});

chrome.permissions.onRemoved.addListener((p) => {
  if (!hasPrivacy(p)) return undefined;
  console.warn('[pxs] WebRTC: разрешение privacy отозвано — настройка «Блокировать WebRTC» выключена; политику без разрешения снять нельзя');
  return state.patchSettings({ webrtc: false }).catch((err) => {
    console.error('[pxs] WebRTC: не удалось записать настройку после отзыва разрешения:', err);
  });
});

