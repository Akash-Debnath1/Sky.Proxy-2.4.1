/**
 * Сверка при старте: что стоит у браузера против того, что записано у нас.
 *
 * Настройка прокси живёт в профиле браузера, наше состояние — в хранилище
 * расширения, и это два независимых места. Разойтись они могут в обе
 * стороны, и обе стороны опасны по-разному:
 *  - у браузера наш прокси применён, у нас «выключено» — человек уверен,
 *    что вышел, а трафик идёт через прокси. Источник истины про «включён
 *    ли» — браузер (решение 02.09): записываем «включено» и подбираем
 *    активный прокси по адресу из настройки — при pac_script адрес читается
 *    из маркера первой строки скрипта (этап 5);
 *  - у нас «включено», у браузера прокси нет — интерфейс врёт в другую
 *    сторону. Применяем прокси заново (режим applyProxy соберёт сам по
 *    настройкам), а если активного в списке уже нет — записываем «выключено».
 * Управление не у нас (другое расширение, политика организации, ключ
 * запуска) — чинить нечего, только записываем уровень.
 *
 * Расхождение ВСЕГДА уходит в консоль отдельной строкой: следующий случай
 * однократного бага этапа 2 должен прийти с доказательством, а не с
 * рассказом.
 *
 * Перенос данных прошлой версии (этап 8) идёт ДО сверки, внутри подготовки
 * хранилища: на исходе 'migrated' состояние уже записано переносом одной
 * операцией вместе с версией формы (enabled — от браузера, levelOfControl
 * не записан — его записывает эта сверка), и сверка идёт как обычно.
 * Исход 'legacy' остаётся только при неудаче переноса — тогда не делаем
 * ничего: состояния нет, писать нечего.
 *
 * Этап 8 (2.6): «выключено» у версии 1.4.7.11 — это наша настройка с
 * режимом direct (старый код ставил её записью настройки, а не снимал её),
 * поэтому после обновления у каждого, кто выключил прокси старым попапом,
 * уровень наш, а адреса в настройке нет. Общее правило «наш уровень = прокси применён»
 * на неё не распространяется: наш уровень и режим direct → настройка
 * снимается (clearProxy пишет «выключено», уровень после снятия, lastError
 * null), строка в консоль, дальше сверка не идёт — у браузера нашей
 * настройки больше нет, состояние «выключено» записано. Сама 2.0.0 режим
 * direct не пишет никогда; правила 7Б ниже не меняются.
 *
 * 7Б (7.5, решение человека 11.09, В1-а и В2): сверка читает тумблер
 * settings.restore («Восстанавливать состояние при старте») — и ТОЛЬКО при
 * старте браузера (reason 'startup'). Тумблер выключен, у нас «включено»:
 *  - у браузера наш прокси применён — а так после обычного перезапуска и
 *    бывает: настройку прокси браузер хранит в профиле и при старте
 *    возвращает сам (золотой тест: «согласны — «включено»»). Ждать, что
 *    она «не восстановится», нечего — снимаем её сами (clearProxy: для
 *    сверки это разрешённый путь мимо очереди) и получаем «выключено»,
 *    свой IP;
 *  - у браузера прокси нет — не применяем заново, только записываем
 *    «выключено».
 * При установке и обновлении расширения (onInstalled) тумблер не
 * читается: обновление приходит ночью само и не должно выключать прокси
 * посреди сеанса. Ветка «у браузера применён, у нас выключено» от
 * тумблера не зависит: браузер уже держит наш прокси, честно записываем
 * «включено».
 *
 * @param {{result: string}} prep итог prepareStorage()
 * @param {string} reason 'startup' | 'install' | 'update' | …
 */
/**
 * 2.1: дописать тип в записи, где его нет.
 *
 * Список 2.0.0 жил без поля type — тип был литералом HTTP. Читатели это
 * понимают (normType), но схема PROXY требует поле, а фильтр по типам и
 * выгрузка опираются на запись, а не на догадку. Поэтому один раз за
 * старт: нет известного типа — ставим HTTP (ровно то, как такие записи и
 * работали), метку догадки не ставим: это не догадка о протоколе, а
 * прежнее поведение. Пишем только когда что-то изменилось, одной
 * операцией — пустая запись будила бы окна зря.
 */
async function normalizeTypes() {
  const list = await state.getProxies();
  let changed = false;
  const next = list.map((p) => {
    if (!p || typeof p !== 'object') return p;
    const t = String(p.type || '').toUpperCase();
    if (PROXY_TYPES.includes(t)) return p;
    changed = true;
    return { ...p, type: 'HTTP' };
  });
  if (!changed) return;
  try {
    await state.setProxies(next);
    console.log('[pxs] в записи без типа дописан HTTP (2.1)');
  } catch (err) {
    console.error('[pxs] не удалось дописать тип в записи:', err);
  }
}

/**
 * 2.3: дописать в хранилище умолчания настроек и состояния.
 *
 * Нормы (normSettings/normState в state.js) подставляют умолчания при
 * ЧТЕНИИ, поэтому расширение работает и без них. Но хранилище, записанное
 * прошлой версией, выглядело «неполным»: settings без tz, state без полей
 * часового пояса. Теперь при старте воркера недостающие ключи один раз
 * дописываются — то, что лежит в chrome.storage.local, совпадает с тем,
 * что видит код, и любой внешний разбор хранилища читается однозначно.
 * Пишем только при расхождении: лишних записей на каждом старте нет.
 */
async function normalizeSettings() {
  try {
    const box = await storage.getMany([KEYS.SETTINGS, KEYS.STATE]);
    const rawS = box[KEYS.SETTINGS];
    const rawT = box[KEYS.STATE];
    const s = normSettings(rawS);
    const t = normState(rawT);
    const patch = {};
    if (!isSettingsObject(rawS) || Object.keys(s).some((k) => !(k in rawS))) patch[KEYS.SETTINGS] = s;
    if (!isSettingsObject(rawT) || Object.keys(t).some((k) => !(k in rawT))) patch[KEYS.STATE] = t;
    if (!Object.keys(patch).length) return;
    await chrome.storage.local.set(patch);
    console.log('[pxs] в настройки дописаны умолчания (2.3)');
  } catch (err) {
    console.error('[pxs] не удалось дописать умолчания настроек:', err);
  }
}

async function reconcile(prep, reason) {
  if (!prepared(prep)) {
    console.log(`[pxs] сверка при старте (${reason}) пропущена: хранилище в состоянии «${prep.result}»`);
    return;
  }

  // 7В: запрос проверки сон воркера не переживает — пометка probing, застрявшая
  // после гашения воркера посреди проверки, снимается стартом (запись только
  // если стояла true — иначе окна вечно показывали бы «Проверяем…»).
  await probeOff();

  const [st, cfg] = await Promise.all([state.getState(), chrome.proxy.settings.get({})]);
  const level = cfg && typeof cfg.levelOfControl === 'string' ? cfg.levelOfControl : 'not_controllable';
  const ours = level === 'controlled_by_this_extension';
  const said = st.enabled ? 'включено' : 'выключено';
  const value = cfg && cfg.value && typeof cfg.value === 'object' ? cfg.value : {};
  const mode = ours && typeof value.mode === 'string' ? `, режим ${value.mode}` : '';

  // Этап 8 (2.6): наша настройка с режимом direct — «выключено» прошлой версии, снимаем.
  if (ours && value.mode === 'direct') {
    await proxy.clearProxy();
    console.log(`[pxs] сверка при старте (${reason}): настройка «напрямую» прошлой версии снята — «выключено»`);
    return;
  }

  if (level === 'controlled_by_other_extensions' || level === 'not_controllable') {
    await state.patchState({ levelOfControl: level });
    console.log(`[pxs] сверка при старте (${reason}): управление не у нас (${level}), состояние «${said}» — только записано`);
    return;
  }

  // 7Б: восстанавливать ли «включено» после старта браузера — по тумблеру.
  const restore = reason !== 'startup' || (await state.getSettings()).restore !== false;

  if (ours === st.enabled) {
    if (st.enabled && !restore) {
      await proxy.clearProxy();
      console.log(`[pxs] сверка при старте (${reason}): восстановление выключено — прокси не включаем, настройка браузера снята`);
      return;
    }
    await state.patchState({ levelOfControl: level });
    console.log(`[pxs] сверка при старте (${reason}): браузер и состояние согласны — «${said}»${mode}`);
    // 7К.2 (А-4): «включено» с обеих сторон ещё не значит, что у браузера та
    // самая настройка: после гашения воркера посреди лечения остаётся
    // временный PAC (сайт напрямую), чужой режим — тоже наш уровень. Настройка
    // собирается по settings заново и переставляется ТОЛЬКО при расхождении
    // текста (ifChanged; при совпадении set не зовётся и строк нет); ошибка
    // не снимается (keepError) — это не новая попытка подключения. Активного
    // в списке нет — как прежде, ничего. При любой причине сверки.
    if (st.enabled) {
      const found = (await state.getProxies()).find((p) => p && p.id === st.activeProxyId);
      if (found) {
        const res = await proxy.applyProxy(found, () => auth.reloadCreds(), { ifChanged: true, keepError: true });
        if (!res.ok) console.warn(`[pxs] сверка при старте: настройка по правилам не переставлена — ${res.message}`);
      }
    }
    return;
  }

  const list = await state.getProxies();

  if (ours) {
    // Прокси применён, а у нас «выключено». Берём сторону браузера.
    const addr = proxy.appliedAddr(value);
    const found = addr ? list.find((p) => p && hostPort(p) === addr) : undefined;
    await state.patchState({
      enabled: true,
      activeProxyId: found ? found.id : st.activeProxyId,
      levelOfControl: level,
    });
    console.warn(`[pxs] РАСХОЖДЕНИЕ при старте (${reason}): у браузера прокси применён${mode}, у нас было «выключено» — записано «включено»${found ? '' : ', адрес из настройки в списке не найден'}`);
    return;
  }

  // У нас «включено», а у браузера прокси нет.
  if (!restore) {
    await state.patchState({ enabled: false, lastError: null, levelOfControl: level });
    console.log(`[pxs] сверка при старте (${reason}): восстановление выключено — прокси не включаем`);
    return;
  }
  const found = list.find((p) => p && p.id === st.activeProxyId);
  if (found) {
    console.warn(`[pxs] РАСХОЖДЕНИЕ при старте (${reason}): у нас «включено», у браузера прокси не применён — применяем заново`);
    const res = await proxy.applyProxy(found, () => auth.reloadCreds());
    if (!res.ok) console.warn(`[pxs] сверка при старте: применить заново не удалось — ${res.message}`);
    return;
  }
  await state.patchState({ enabled: false, lastError: null, levelOfControl: level });
  console.warn(`[pxs] РАСХОЖДЕНИЕ при старте (${reason}): у нас «включено», у браузера прокси нет, активного прокси в списке нет — записано «выключено»`);
}

/**
 * Проверка при подключении на старте браузера (7В, четвёртая выдача —
 * решение человека 11.09, В1-а). Браузер сам возвращает настройку прокси
 * из профиля, и после сверки «согласны — включено» прокси стоит так, как
 * будто его только что включили, — а вердикта о нём нет: закрыли Chrome
 * посреди проверки — пометка снята стартом, мёртвый прокси стоял бы
 * «Подключено» до настоящего трафика. Поэтому после сверки при старте
 * браузера (только onStartup: обновление расширения ночью ничего не
 * трогает; при выключенном restore прокси снят самой сверкой) при
 * включённом прокси и нашем управлении идёт та же проверка, что после
 * команды окна — с тем же исходом: «Подключено», красный через 8 с,
 * переключение при тумблере. Под чужим управлением запросы шли бы не
 * через наш прокси — проверять нечего.
 *
 * @param {{result: string}} prep итог prepareStorage()
 * @param {string} reason
 */
async function probeAtStart(prep, reason) {
  if (reason !== 'startup') return;
  if (!prepared(prep)) return;
  try {
    const st = await state.getState();
    if (!st.enabled || st.levelOfControl !== 'controlled_by_this_extension') return;
    await probeAfter('startup');
  } catch (err) {
    console.error('[pxs] проверка при старте не запустилась:', err);
  }
}

/*
 * 7Б: при одном старте браузера сюда могут прийти два события подряд —
 * onStartup и onInstalled (обновление расширения или самого браузера,
 * применённое при запуске). Раньше две сверки шли внахлёст и делали одно
 * и то же; теперь сверка при старте умеет снимать настройку прокси по
 * тумблеру restore, и вторая, прочитав состояние до записи первой, могла
 * бы применить прокси обратно. Поэтому старты идут по очереди. Память
 * воркера, в ней только работа в полёте — допустимо.
 */
let startLine = Promise.resolve();

/**
 * Подготовка, следом сверка, следом проверка при подключении, если после
 * сверки прокси остался включённым (7В, старт браузера), следом политика
 * WebRTC по итоговому состоянию (7А), следом значок (6.1; с 7Г — вместе с
 * плашкой: после перезапуска браузера значок и плашка возвращаются к
 * манифесту, поэтому выставляются заново из хранилища),
 * следом аккаунт (этап 6), следом файл сообщений (7И: будильник и забор
 * при кеше старше CONFIG_TTL_MIN). Ошибка одного шага не роняет остальные и не
 * мешает подготовке.
 */
function prepareAndReconcile(reason) {
  const turn = startLine.then(() => prepareStorage()).then(async (prep) => {
    try {
      await reconcile(prep, reason);
      /* 2.1/2.3: normalizeTypes и normalizeSettings теперь выполняются в
         prepareStorage() — одной точкой раньше, до сверки. Здесь их нет,
         чтобы форма данных нормализовалась ровно один раз. */
    } catch (err) {
      console.error('[pxs] сверка при старте не удалась:', err);
    }
    await probeAtStart(prep, reason);   // своих ошибок не бросает
    await applyWebrtc('start');   // своих ошибок не бросает — пишет в консоль
    await syncTz('start');   // 2.2: пояс страниц — после сверки, когда известен активный прокси
    geo.run().catch(() => {});   // 2.4: страны для адресов без флага — не задерживает старт
    /* 2.6.1: свой адрес нужен один раз — с ним сравнивается выходной, чтобы
       честно сказать «этот сайт всё ещё видит вас». Прокси выключен и адреса
       ещё нет — мерим; включён — мерить будет фон после подключения. */
    state.getState()
      .then((s) => (s.enabled || s.directIp ? null : proveExit('start')))
      .catch(() => {});
    // Этап 8: на хранилище прошлой версии, где перенос не удался ('legacy'),
    // значок не перерисовывается — перерисовка пишет state.badgeCount, и наш
    // ключ state появился бы до переноса, а перенос при следующем старте
    // счёл бы хранилище испорченным (наши ключи без версии) и не повторился
    // бы никогда. Значок и так манифестный — «выключено».
    if (prepared(prep)) await redrawBadge('start');   // своих ошибок не бросает — пишет в консоль
    try {
      await accountAtStart(prep, reason);
    } catch (err) {
      console.error('[pxs] аккаунт при старте не обработан:', err);
    }
    try {
      await configAtStart(prep, reason);   // 7И
    } catch (err) {
      console.error('[pxs] файл сообщений при старте не обработан:', err);
    }
  });
  startLine = turn.catch(() => {});
  return turn;
}

/*
 * Слушатели возвращают обещание работы наружу.
 *
 * Честно: гарантией это не является. Браузер не обязан дожидаться обещания
 * и вправе погасить воркер посреди работы. Настоящая защита — короткая,
 * повторно безопасная работа и запись одной операцией.
 */
chrome.runtime.onInstalled.addListener((details) => {
  console.log(`[pxs] событие установки или обновления: ${details.reason}`);
  return prepareAndReconcile(details.reason);
});

chrome.runtime.onStartup.addListener(() => {
  console.log('[pxs] запуск браузера');
  return prepareAndReconcile('startup');
});

/* ── перехват управления на лету (7Б, 7.5; дыра 6.1 В3) ──────────────
 * Сверка при старте ловит чужое управление только при старте. Если другое
 * прокси-расширение включили посреди сеанса, наша настройка перестаёт
 * действовать, а состояние, значок и попап говорили «включено».
 * Браузер сообщает о каждой смене настройки прокси (и о смене уровня
 * управления) событием chrome.proxy.settings.onChange — в том числе о
 * наших собственных set и clear.
 *
 * Правило: управление ушло (другое расширение, политика, ключ запуска)
 * при записанном «включено» — записать «выключено» и уровень; значок
 * станет чёрно-белым сам (по подписке на enabled), попап и страница
 * покажут «выключено» по подписке. Вернулось управление — записать
 * уровень и НЕ включать прокси самим: включит человек. При
 * controllable_by_this_extension поле enabled не трогается вовсе: так
 * браузер отвечает и на наше собственное выключение, и лишняя запись
 * «управление ушло» здесь была бы враньём. Свой уровень после set
 * записывает applyProxy — здесь та же запись, без изменения.
 */
const LOST_LEVELS = Object.freeze(['controlled_by_other_extensions', 'not_controllable']);

async function onControlChange(level) {
  const st = await state.getState();
  if (LOST_LEVELS.includes(level)) {
    if (st.enabled) {
      await state.patchState({ enabled: false, levelOfControl: level, lastError: null });
      console.warn(`[pxs] управление прокси перехвачено (${level}) — записано «выключено», включит человек`);
      return;
    }
    await state.patchState({ levelOfControl: level });
    return;
  }
  if (level === 'controllable_by_this_extension' && LOST_LEVELS.includes(st.levelOfControl)) {
    console.log('[pxs] управление прокси вернулось — прокси не включаем, включит человек');
  }
  await state.patchState({ levelOfControl: level });
}

chrome.proxy.settings.onChange.addListener((details) => {
  const level = details && typeof details.levelOfControl === 'string' ? details.levelOfControl : 'not_controllable';
  return onControlChange(level).catch((err) => {
    console.error('[pxs] смена управления прокси не обработана:', err);
  });
});

/**
 * Включить прокси по его идентификатору.
 *
 * Порядок внутри applyProxy важен: сначала состояние, затем подготовка
 * логина и пароля, и только потом настройка уходит браузеру. Обратный
 * порядок оставил бы щель, в которую успел бы проскочить запрос без
 * данных для входа. Режим (списки или нет) applyProxy выбирает сам.
 *
 * Ответ по контракту интерфейса: { ok:true } либо { ok:false, error }.
 * error — короткий код, текст к нему подбирает окно по своему словарю:
 * 'notFound' — такого прокси в списке нет; 'controlled_by_other_extensions'
 * и 'not_controllable' — управление не у нас; 'bad' — настройку из записи
 * собрать не удалось (адрес пустой или порт вне границ) либо браузер её
 * не принял.
 */
async function enableProxy(id) {
  const list = await state.getProxies();
  const found = list.find((p) => p && p.id === id);
  if (!found) return { ok: false, error: 'notFound' };

  const res = await proxy.applyProxy(found, () => auth.reloadCreds());
  if (res.ok) return { ok: true };
  const blocked = res.level === 'controlled_by_other_extensions' || res.level === 'not_controllable';
  return { ok: false, error: blocked ? res.level : 'bad' };
}

/**
 * Повторное применение по подписке на settings (этап 5): списки изменились
 * при включённом прокси — применить заново тот же активный прокси.
 * Сравнивать с прошлыми значениями в памяти воркера нельзя — сон её
 * стирает, поэтому applyProxy с ifChanged сравнивает собранную настройку с
 * той, что стоит у браузера, и при совпадении не делает ничего. Прокси
 * выключен или активного в списке нет — ничего не делать.
 *
 * 7Л: команды окна { cmd:'lists' } больше нет (решение человека 19.09,
 * В7) — правка списков из попапа и со страницы приходит только этой
 * подпиской и вкладку не перезагружает. Булев ответ оставлен как был
 * (прокси действует и настройка на месте); подписка его не читает, читает
 * команда siteReload (правка человека 20.09, ниже): она применяет списки
 * тем же вызовом и лишь потом перезагружает вкладку.
 *
 * @returns {Promise<boolean>} прокси включён и настройка на месте
 */
async function reapplyLists() {
  const st = await state.getState();
  if (!st.enabled) return false;
  const list = await state.getProxies();
  const found = list.find((p) => p && p.id === st.activeProxyId);
  if (!found) return false;

  // keepError (7Ж, находка человека 18.09): меняются списки, не прокси —
  // «не отвечает» / «неверный логин» остаются, пока прокси не включат заново
  const res = await proxy.applyProxy(found, () => auth.reloadCreds(), { ifChanged: true, keepError: true });
  if (!res.ok) console.warn(`[pxs] повторное применение по настройкам не удалось — ${res.message}`);
  return res.ok;
}

/**
 * Сообщения окон (этап 4). Контракт принят как есть, чтобы окна и фон не
 * разошлись:
 *   { cmd:'enable',  id } → включить прокси id
 *   { cmd:'disable' }     → выключить
 *   { cmd:'switch',  id } → переключить на id при включённом
 * Ответ { ok:true } либо { ok:false, error }.
 * Этап 6:
 *   команда keyLoad с полем key → проверить ключ API и получить список аккаунта;
 *   ответ { ok:true, items } либо { ok:false, error: 'bad'|'expired'|'empty'|'net' }.
 *   команда keyRefresh → обновить кеш и добавленные по ключу из настроек
 *   (кнопка «Обновить сейчас», решение человека 10.09); ответ
 *   { ok:true, count } либо { ok:false, error: 'bad'|'expired'|'empty'|'net'|'noKey' }.
 *   Через очередь применений не идут — это не настройка браузера.
 * 7Л (решение человека 19.09, В7): команды lists, которую 7Ж заводила для
 *   попапа (применить списки и перезагрузить вкладку), НЕТ: правка списков
 *   из любого окна идёт записью settings через state.js и приходит сюда
 *   подпиской (reapplyLists через очередь применений, низ файла), вкладка при этом не
 *   перезагружается — это не смена прокси.
 * 7Л (правка человека 20.09, 8): одно исключение — тумблер строки «Прокси
 *   для:» попапа. После записи списка попап шлёт { cmd:'siteReload' }: фон
 *   применяет списки через очередь (reapplyLists — списки уже в хранилище,
 *   подписка их тоже применит, повтор с ifChanged безвреден) и затем
 *   перезагружает активную вкладку по тумблеру settings.reload
 *   (reloadActiveTab). Ответ { ok:true, reloaded }. Только строка: панель
 *   адресов, селектор режима и страница команду не шлют.
 *
 * 'switch' делает то же, что 'enable': applyProxy переписывает настройку
 * браузера и активный прокси разом, отдельного пути «сначала снять, потом
 * поставить» не нужно — он и оставил бы трафик без прокси на мгновение.
 * Разница между командами смысловая, по ней видно, что имело в виду окно.
 *
 * Слушатель СИНХРОННЫЙ и возвращает true — это единственный способ сказать
 * браузеру «ответ будет позже, канал не закрывай». Ответ уходит всегда,
 * и на ошибку тоже: окно, не дождавшееся ответа, зависло бы в «Подключение…».
 *
 * Этап 5: команды идут через очередь применений (inLine), как и повторное
 * применение по подписке.
 *
 * 7Б (7.7): после удачных enable и switch от окна — перезагрузка активной
 * вкладки по тумблеру settings.reload (reloadActiveTab ниже), и тогда в
 * ответе окну reloaded: true — окно приписывает к своему тосту хвост
 * «вкладка перезагружена». Только этот путь: переключение при обрыве,
 * самолечение, повторное применение по подписке и правка списков (7Л)
 * вкладку не трогают.
 * Перезагрузка идёт после очереди, не внутри неё — это не настройка
 * браузера, и следующую команду она задерживать не должна.
 *
 * 7В (7.2): после тех же удачных enable и switch от окна — проверка при
 * подключении (probeAfter ниже): один запрос через новый прокси, ответа
 * окну сам запрос НЕ задерживает — «подключено» пишется при применении
 * настройки, проверка идёт секунду-две следом (DECISIONS 11.09, п. 3);
 * ответ ждёт только запись пометки state.probing (вторая выдача 7В):
 * по ней окна показывают «Проверяем…». Запускается до перезагрузки
 * вкладки, чтобы быть первым запросом через новый прокси. Только этот
 * путь: переключение при обрыве, самолечение и повторное применение по
 * подписке проверку не зовут. disable снимает пометку (probeOff).
 *
 * Старый обработчик временной страницы этапа 2 (proxy.enable / proxy.disable /
 * proxy.control) выброшен, а не переписан.
 */
chrome.runtime.onMessage.addListener((message, sender, sendResponse) => {
  const cmd = message && message.cmd;

  const answer = (work) => {
    work
      .then(sendResponse)
      .catch((err) => {
        console.error('[pxs] команда окна упала:', cmd, err);
        sendResponse({ ok: false, error: 'failed' });
      });
    return true;
  };

  if (cmd === 'enable' || cmd === 'switch') {
    return answer(
      inLine(() => enableProxy(typeof message.id === 'string' ? message.id : ''))
        .then((res) => {
          if (!res.ok) return res;
          /* 2.6.1: доказательство выхода — фоном, ответа окну не задерживает */
          proveExit(cmd);
          // 7В: пометка probing уходит в state до ответа окну (иначе окно успело бы
          // нарисовать «Подключено» и лишь потом «Проверяем…»); сам запрос — следом.
          return probeAfter(cmd)
            .then(() => reloadActiveTab(cmd))
            .then((reloaded) => (reloaded ? { ...res, reloaded: true } : res));
        }),
    );
  }
  if (cmd === 'disable') {
    return answer(inLine(() => proxy.clearProxy().then(() => probeOff()).then(() => {
      proveExit('disable');   /* 2.6.1: запомнить свой адрес — с ним сравнивается выход */
      return { ok: true };
    })));
  }
  if (cmd === 'checkExit') {
    /* 2.6.1: перепроверить по клику из окна (без ответа — окно ждёт подписку) */
    proveExit('manual');
    return answer(Promise.resolve({ ok: true }));
  }
  if (cmd === 'siteReload') {
    // 7Л (правка человека 20.09, 8): применить списки из хранилища и перезагрузить
    // активную вкладку по тумблеру reload — после очереди, как у enable/switch
    return answer(
      inLine(() => reapplyLists()).then(() => reloadActiveTab(cmd)).then((reloaded) => ({ ok: true, reloaded })),
    );
  }
  /* 2.1: проверка протокола (кнопка «Проверить тип»). Прокси передаётся
     полями, а не id: проверять можно и ещё не добавленную строку из
     разбора вставки. Через очередь применений не идёт — прокси выключен,
     и пробная настройка живёт внутри самой проверки. */
  if (cmd === 'typeCheck') {
    return answer(typecheck.checkType(message.proxy));
  }
  /* 2.4: страна по адресу — проход по списку и одна строка из меню */
  if (cmd === 'geoRun') {
    return answer(geo.run().then((n) => ({ ok: true, changed: n })));
  }
  if (cmd === 'geoOne') {
    return answer(geo.one(typeof message.id === 'string' ? message.id : ''));
  }
  if (cmd === 'keyLoad') {
    return answer(loadKey(message.key));
  }
  if (cmd === 'keyRefresh') {
    return answer(refresh('manual'));
  }
  return false;
});

/**
 * Перезагрузить активную вкладку после включения или переключения из окна
 * (7Б, 7.7, тумблер «Перезагружать вкладку при смене прокси»). После enable
 * и switch и по команде siteReload от тумблера строки попапа (правка
 * человека 20.09, 8); прочая правка списков вкладку не перезагружает (7Л).
 *
 * Разрешения tabs у расширения нет и не будет (новое разрешение выключило
 * бы расширение у всех при обновлении, 3.6): chrome.tabs.query и
 * chrome.tabs.reload его не требуют, а адрес вкладки (tab.url) браузер
 * отдаёт по host_permissions <all_urls> — только для http и https.
 * Служебные страницы (chrome://, страницы расширений) адреса не дают —
 * их не трогаем: у них нет запроса, который стоило бы повторить, а
 * страница расширения, перезагрузившись, потеряла бы своё окно. Вкладка —
 * активная в последнем активном окне: под попапом это та страница, с
 * которой человек его открыл.
 *
 * Ошибка здесь не ошибка команды: прокси уже включён. Пишем в консоль,
 * отвечаем «не перезагружена».
 *
 * @param {string} cmd для строки в консоли
 * @returns {Promise<boolean>} перезагружена ли вкладка
 */
async function reloadActiveTab(cmd) {
  try {
    const settings = await state.getSettings();
    if (settings.reload !== true) return false;
    const tabs = await chrome.tabs.query({ active: true, lastFocusedWindow: true });
    const tab = Array.isArray(tabs) ? tabs[0] : undefined;
    if (!tab || !Number.isInteger(tab.id) || typeof tab.url !== 'string' || !/^https?:/i.test(tab.url)) return false;
    await chrome.tabs.reload(tab.id);
    console.log(`[pxs] вкладка перезагружена после команды ${cmd}`);
    return true;
  } catch (err) {
    console.warn('[pxs] вкладка не перезагружена:', err);
    return false;
  }
}

/* ── горячие клавиши (7Д, 7.4) ────────────────────────────────────────
 * Раздел commands манифеста: toggle-proxy (Ctrl+Shift+1 по умолчанию) —
 * включить или выключить прокси; next-proxy (Ctrl+Shift+2) — следующий
 * по кругу; _execute_action (Ctrl+Shift+5) — открыть окно расширения
 * (встроенная команда браузера, сюда не приходит, обработчика нет).
 * Сочетания не global: глобальные ловят нажатия в других программах.
 * Прежнего Ctrl+Shift+0 («выключить» из 1.4.7.11) нет — одно сочетание
 * на включение и выключение. Одиннадцатый слушатель — на верхнем уровне,
 * синхронный, работа возвращается наружу обещанием.
 *
 * Пути те же, что у команд окон: toggle при включённом прокси — как
 * disable (очередь → clearProxy → probeOff), при выключенном — как enable
 * активного (очередь → enableProxy(activeProxyId) → проверка при
 * подключении probeAfter('hotkey')); next — как switch на следующего по
 * кругу после активного, минуя gone и истёкшие (isExpired из format.js —
 * та же проверка, что у переключения при обрыве). Активный включается и
 * истёкшим, и gone — как из окна, это воля человека (ответ проверяющего
 * чата 21.09, п. 3); next их пропускает (промт 7Д). Состояние и список
 * читаются ВНУТРИ очереди: два быстрых нажатия идут друг за другом, а не
 * по одному снимку.
 *
 * Отличия от команд окна: вкладка НЕ перезагружается (решение плана 7.4:
 * окна закрыты, хвост тоста tabReloaded показать некому — reloadActiveTab
 * по клавишам не зовётся), ответа окну нет, тостов и системных
 * уведомлений нет — отказ (нет активного, прокси не включился, управление
 * не у нас) уходит только в консоль, состояние не трогается (ответ
 * 21.09, п. 4). Первым делом читается settings.hotkeys — тумблер «Горячие
 * клавиши» на странице (решение человека 19.09, п. 6): снять сочетания
 * программно браузер не даёт, поэтому при выключенном тумблере команда
 * приходит, и здесь она ничего не делает, кроме строки в консоль. По
 * умолчанию тумблер выключен (правка человека 21.09): без явного «вкл»
 * на странице сочетания не действуют.
 * Адреса прокси в консоль не пишутся — только номер в списке.
 */
chrome.commands.onCommand.addListener((command) => runHotkey(typeof command === 'string' ? command : ''));

async function runHotkey(command) {
  try {
    const settings = await state.getSettings();
    if (settings.hotkeys === false) {
      console.log(`[pxs] горячие клавиши выключены в настройках — команда ${command} пропущена`);
      return;
    }
    if (command === 'toggle-proxy') await hotkeyToggle();
    else if (command === 'next-proxy') await hotkeyNext();
    else console.warn(`[pxs] горячая клавиша: неизвестная команда ${command}`);
  } catch (err) {
    console.error(`[pxs] горячая клавиша ${command} упала:`, err);
  }
}

/** toggle-proxy: включён → выключить (путь disable); выключен → включить активный (путь enable). */
async function hotkeyToggle() {
  const res = await inLine(async () => {
    const st = await state.getState();
    if (st.enabled) {
      await proxy.clearProxy();
      await probeOff();
      return { ok: true, off: true };
    }
    if (!st.activeProxyId) return { ok: false, error: 'noActive' };
    return enableProxy(st.activeProxyId);
  });
  if (res.off) {
    console.log('[pxs] горячая клавиша toggle-proxy: прокси выключен');
    return;
  }
  if (!res.ok) {
    if (res.error === 'noActive') console.log('[pxs] горячая клавиша toggle-proxy: активного прокси нет — ничего не делаем');
    else console.warn(`[pxs] горячая клавиша toggle-proxy: прокси не включился (${res.error})`);
    return;
  }
  console.log('[pxs] горячая клавиша toggle-proxy: прокси включён');
  await probeAfter('hotkey');
}

/** next-proxy: следующий по кругу после активного без gone и истёкших; один годный или ни одного — ничего. */
async function hotkeyNext() {
  const res = await inLine(async () => {
    const [st, list] = await Promise.all([state.getState(), state.getProxies()]);
    const idx = list.findIndex((p) => p && p.id === st.activeProxyId);
    const start = idx < 0 ? 0 : idx + 1;
    for (let k = 0; k < list.length; k++) {
      const i = (start + k) % list.length;
      const p = list[i];
      if (!p || p.id === st.activeProxyId || p.gone === true || isExpired(p)) continue;
      const r = await enableProxy(p.id);
      return { ...r, pos: i + 1, total: list.length };
    }
    return { ok: false, error: 'none', total: list.length };
  });
  if (res.error === 'none') {
    console.log(`[pxs] горячая клавиша next-proxy: переключаться не на кого (в списке ${res.total}) — ничего не делаем`);
    return;
  }
  if (!res.ok) {
    console.warn(`[pxs] горячая клавиша next-proxy: прокси ${res.pos} из ${res.total} не включился (${res.error})`);
    return;
  }
  console.log(`[pxs] горячая клавиша next-proxy: переключились на прокси ${res.pos} из ${res.total}`);
  await probeAfter('hotkey');
}

/* ── аккаунт proxys.io по ключу API (этап 6) ──────────────────────────
 * Ключ — импорт, не синхронизация (мастер-промт 3.7): ничего не
 * добавляется и не удаляется само. Фон умеет три вещи: проверить ключ и
 * получить список (keyLoad от страницы), обновить данные уже добавленных
 * прокси по этому списку и делать то же самое раз в шесть часов по
 * будильнику. Ключ живёт только в settings.apiKey; в консоль, ответы окнам
 * и сообщения об ошибках он не попадает — как и адрес запроса.
 */

/**
 * Один заход к API: запрос плюс разбор. Ошибки сводятся к четырём видам, у
 * каждого свой текст на странице: 'bad' — ключ не принят, 'expired' —
 * ключ просрочен, 'empty' — заказов не найдено (код 1002, 7И — правка
 * человека 24.09; путь тот же, что у 'bad'), 'net' — сервер недоступен
 * (сеть, таймаут, не-JSON).
 *
 * @param {string} key
 * @returns {Promise<{ok: true, items: Object[], dropped: number}|{ok: false, error: string}>}
 */
async function loadFromApi(key) {
  const got = await api.fetchV2(key);
  if (!got.body) return { ok: false, error: 'net' };
  const parsed = api.parseV2(got.body);
  if (!parsed.ok) return { ok: false, error: parsed.kind };
  return { ok: true, items: parsed.items, dropped: parsed.dropped };
}

/**
 * Обновить данные уже добавленных прокси по списку аккаунта (3.7).
 *
 * Для каждого прокси с src 'pxs' ищется запись аккаунта: сначала по
 * orderId + ip + port, при промахе — по ip + port (решение сессии 10.09:
 * продление может выдать новый номер заказа на тот же адрес — иначе
 * продлённый прокси навсегда стал бы «нет в аккаунте»). Нашлась — логин,
 * пароль, страна, срок и номер заказа берутся из аккаунта (страна из
 * аккаунта побеждает любую отметку, 3.9; нет страны в записи — снимается;
 * 7К.2, В-4: неизвестный срок и пустые логин или пароль известные не
 * затирают), метка gone снимается. Не нашлась — gone: true. Ручные не трогаются;
 * id, заметки и порядок остаются; ничего не добавляется и не удаляется.
 *
 * Список перечитывается СРАЗУ перед записью и пишется одним setProxies —
 * и только если что-то действительно изменилось: лишняя запись разбудила
 * бы окна и обработчик авторизации на ровном месте.
 *
 * @param {Object[]} items записи аккаунта в нашей форме, без id
 * @param {string} reason для строки в консоли
 */
async function updateAdded(items, reason) {
  const byOrder = new Map();
  const byAddr = new Map();
  for (const a of items) {
    const addr = `${a.ip}:${a.port}`;
    if (!byAddr.has(addr)) byAddr.set(addr, a);
    if (Number.isInteger(a.orderId)) byOrder.set(`${a.orderId}|${addr}`, a);
  }

  const list = await state.getProxies();
  const inList = new Set(list.map((p) => `${p.ip}:${p.port}`));
  const added = items.filter((a) => inList.has(`${a.ip}:${a.port}`)).length;

  let changed = false;
  let gone = 0;
  const next = list.map((p) => {
    if (p.src !== constants.SRC.PXS) return p;
    const addr = `${p.ip}:${p.port}`;
    const a = (Number.isInteger(p.orderId) && byOrder.get(`${p.orderId}|${addr}`)) || byAddr.get(addr);
    let upd;
    if (a) {
      upd = { ...p };
      // 7К.2 (В-4): «срока не знаем» из аккаунта (exp null без expUnlimited — так
      // читается любая смена формата поля) известный срок записи не затирает;
      // пустой логин или пароль при непустых прежних — прежние остаются. Запись
      // при этом не выбрасывается и gone не ставится.
      if (!(a.exp === null && !a.expUnlimited)) {
        upd.exp = a.exp;
        upd.expUnlimited = a.expUnlimited;
      }
      const prevCreds = typeof p.login === 'string' && p.login !== '';
      if (!prevCreds || (a.login !== '' && a.pass !== '')) {
        upd.login = a.login;
        upd.pass = a.pass;
      }
      if (a.cc) upd.cc = a.cc; else delete upd.cc;
      if (Number.isInteger(a.orderId)) upd.orderId = a.orderId;
      delete upd.gone;
    } else {
      gone += 1;
      upd = { ...p, gone: true };
    }
    if (JSON.stringify(upd) === JSON.stringify(p)) return p;
    changed = true;
    return upd;
  });

  if (changed) await state.setProxies(next);
  console.log(`[pxs] аккаунт (${reason}): ${items.length} записей, добавлено ${added}, новых ${items.length - added}, нет в аккаунте ${gone}${changed ? '' : ' — список без изменений'}`);
}

/**
 * Будильник обновления: существует ровно тогда, когда ключ привязан,
 * включён settings.autoUpdate и кеш аккаунта не помечен отказом ключа
 * (после 'bad' / 'expired' обновлять нечего, пока ключ не заменят).
 * ЕДИНСТВЕННОЕ место, где заводится будильник аккаунта (второй будильник
 * проекта — файл сообщений, configAlarm ниже, 7И). Уже заведённый не
 * перезаводится — иначе каждый старт браузера сдвигал бы период заново;
 * reset заводит заново нарочно: после удачной загрузки по ключу отсчёт
 * шести часов идёт от неё.
 *
 * @param {{reset?: boolean, settings?: Object}} [opts]
 */
async function syncAlarm(opts) {
  const reset = !!(opts && opts.reset);
  const settings = (opts && opts.settings) || await state.getSettings();
  const account = await state.getAccount();
  const want = settings.apiKey !== '' && settings.autoUpdate === true && !(account && account.error);
  const existing = await chrome.alarms.get(constants.ALARMS.API_REFRESH);

  if (want) {
    if (existing && !reset) return;
    await chrome.alarms.create(constants.ALARMS.API_REFRESH, { periodInMinutes: constants.REFRESH_PERIOD_MIN });
    console.log(`[pxs] будильник обновления аккаунта ${existing ? 'заведён заново' : 'заведён'}, период ${constants.REFRESH_PERIOD_MIN} мин`);
    return;
  }
  if (existing) {
    await chrome.alarms.clear(constants.ALARMS.API_REFRESH);
    console.log('[pxs] будильник обновления аккаунта снят');
  }
}

/**
 * Проверить ключ и получить список аккаунта — команда страницы keyLoad.
 *
 * Ключ пишется в settings ТОЛЬКО после удачного ответа и только если за
 * время загрузки ключ в настройках не менялся вовсе (решение сессии 10.09
 * — строже, чем «не стал другим непустым»: «Отвязать» во время загрузки
 * делает его пустым, и ответ не должен привязать ключ обратно). Ответ при
 * этом всё равно отдаётся — страница сама решает по своему поколению,
 * применять ли его. Отказ ключа или сети — ничего не пишется.
 *
 * @param {*} rawKey
 * @returns {Promise<{ok: true, items: Object[]}|{ok: false, error: string}>}
 */
async function loadKey(rawKey) {
  const key = typeof rawKey === 'string' ? rawKey.trim() : '';
  if (!key) return { ok: false, error: 'bad' };
  if (key.length > schema.SETTINGS.apiKey.max) {
    console.warn('[pxs] ключ длиннее, чем допускает схема — не принят');
    return { ok: false, error: 'bad' };
  }

  const before = (await state.getSettings()).apiKey;
  const res = await loadFromApi(key);
  if (!res.ok) return { ok: false, error: res.error };

  const now = (await state.getSettings()).apiKey;
  if (now !== before) {
    console.log('[pxs] ключ принят, но за время загрузки ключ в настройках изменился — ответ не записан');
    return { ok: true, items: res.items };
  }

  await state.patchSettings({ apiKey: key });
  await state.setAccount({ at: Date.now(), items: res.items, error: null });
  console.log(`[pxs] ключ принят: в аккаунте ${res.items.length} записей${res.dropped ? `, пропущено негодных ${res.dropped}` : ''}`);
  await updateAdded(res.items, 'по ключу');
  await syncAlarm({ reset: true });
  return { ok: true, items: res.items };
}

/*
 * Обновление в работе. Переменная верхнего уровня разрешена явно (3.2):
 * в ней только работа в полёте, после пробуждения воркера она пуста.
 * Будильник и команда keyRefresh со страницы, совпав по времени, делят
 * один заход.
 */
let refreshing = null;

/**
 * Обновить кеш аккаунта и данные добавленных по ключу из настроек.
 * Запускается из будильника, при старте браузера (если с последней
 * удачной загрузки прошло больше периода — будильник мог не сработать,
 * пока браузер был закрыт) и вручную — команда keyRefresh со страницы.
 *
 * Удача → кеш и добавленные обновлены. 'bad' / 'expired' / 'empty' (7И) →
 * ключ НЕ стирается (решение 10.09): причина пишется в account.error,
 * страница показывает «ключ больше не действует», будильник снимается.
 * 'net' — временное, ничего не меняется.
 *
 * @param {string} reason
 * @returns {Promise<{ok: boolean, error?: string, count?: number}>}
 */
function refresh(reason) {
  if (!refreshing) {
    refreshing = runRefresh(reason).finally(() => {
      refreshing = null;
    });
  }
  return refreshing;
}

async function runRefresh(reason) {
  const settings = await state.getSettings();
  if (settings.apiKey === '') {
    console.log(`[pxs] обновление аккаунта (${reason}): ключ не привязан — нечего обновлять`);
    return { ok: false, error: 'noKey' };
  }

  const res = await loadFromApi(settings.apiKey);

  if (res.ok) {
    await state.setAccount({ at: Date.now(), items: res.items, error: null });
    await updateAdded(res.items, reason);
    await syncAlarm();
    return { ok: true, count: res.items.length };
  }
  if (res.error === 'net') {
    console.warn(`[pxs] обновление аккаунта (${reason}): сервер недоступен — кеш и ключ оставлены как есть`);
    return res;
  }
  const previous = await state.getAccount();
  await state.setAccount({
    at: previous ? previous.at : 0,
    items: previous ? previous.items : [],
    error: res.error,
  });
  await syncAlarm();
  console.warn(`[pxs] обновление аккаунта (${reason}): ${res.error === 'empty' ? 'заказов не найдено' : 'ключ больше не действует'} (${res.error}) — обновления остановлены, ключ и прокси не тронуты`);
  return res;
}

/**
 * Аккаунт при старте браузера и при установке или обновлении расширения.
 * Будильник заводится заново при тех же условиях — будильники переживают
 * перезапуск браузера, но не переустановку расширения. Кеш старше периода,
 * пустой или помеченный отказом ключа перечитывается один раз (ключ могли
 * продлить в кабинете; будильник при отказе не возвращается, пока ответ не
 * удачный). Только здесь, а не при каждом пробуждении воркера: при
 * недоступном сервере запрос уходил бы при каждом пробуждении.
 *
 * @param {{result: string}} prep итог prepareStorage()
 * @param {string} reason
 */
async function accountAtStart(prep, reason) {
  if (!prepared(prep)) return;
  const settings = await state.getSettings();
  if (settings.apiKey === '') return;

  await syncAlarm({ settings });
  if (!settings.autoUpdate) return;

  const account = await state.getAccount();
  const age = account ? Date.now() - account.at : Infinity;
  const stale = !account || account.error !== null || age > constants.REFRESH_PERIOD_MIN * 60000;
  if (stale) {
    await refresh(reason);
  } else {
    console.log(`[pxs] аккаунт при старте (${reason}): кеш свежий, ${Math.round(age / 60000)} мин — обновление по будильнику`);
  }
}

/**
 * Будильники — два имени в одном слушателе (7И: второй, ALARMS.CONFIG, —
 * файл сообщений; слушатель тот же, одиннадцатый не добавляется). Слушатель
 * на верхнем уровне, работа возвращается наружу.
 */
chrome.alarms.onAlarm.addListener((alarm) => {
  const name = alarm && alarm.name;
  if (name === constants.ALARMS.API_REFRESH) {
    return refresh('alarm').catch((err) => {
      console.error('[pxs] обновление по будильнику упало:', err);
    });
  }
  if (name === constants.ALARMS.CONFIG) {
    return fetchRemoteIfStale('alarm').catch((err) => {
      console.error('[pxs] файл сообщений по будильнику упал:', err);
    });
  }
  return undefined;
});

/**
 * Настройки изменились — что это значит для аккаунта (этап 6). Прежних
 * значений в памяти воркера нет (сон стирает), поэтому всё по текущим:
 * ключ пуст → кеш аккаунта стирается, если ещё не стёрт, и будильник
 * снимается; ключ есть → будильник приводится к правилу syncAlarm (тумблер
 * «Обновлять список из аккаунта» заводит и снимает его этим же путём).
 */
async function accountOnSettings(settings) {
  if (settings.apiKey === '') {
    const account = await state.getAccount();
    if (account !== null) {
      await state.setAccount(null);
      console.log('[pxs] ключ отвязан: кеш аккаунта очищен, обновления остановлены');
    }
  }
  await syncAlarm({ settings });
}

/* ── файл сообщений proxys.io (7И, подготовительный этап) ─────────────
 * Файл на хостах SITE_HOSTS (адрес CONFIG_PATH — пока заглушка, настоящий
 * впишет этап 9): баннеры для панели уведомлений с уровнями «Срочно» /
 * «Важно» / «Классическое» и домен ссылок интерфейса (site). Настоящего
 * файла у разработчиков ещё нет — до него каждый забор кончается 'net',
 * одной строкой в консоль, и всё остальное работает как до 7И.
 *
 * Забор — api.fetchConfig (тот же обход хостов, что у API, без ключа) при
 * старте браузера и при установке/обновлении (после аккаунта, только при
 * готовом хранилище — prepared(): ready, marked, с этапа 8 migrated — как
 * accountAtStart) и по будильнику
 * ALARMS.CONFIG раз в CONFIG_PERIOD_MIN; и там, и там файл берётся только
 * при кеше старше CONFIG_TTL_MIN (пять часов при периоде шесть — почему
 * меньше периода, см. constants.js) либо без кеша. Будильник
 * заводится всегда (ключ не нужен — файл не про аккаунт), уже заведённый
 * не перезаводится. Кеш — седьмой ключ remote { at, site, banners, error }
 * через state.js (setRemote — только отсюда): удача → всё заново, error
 * null; отказ ('net' — оба хоста, 'schema' — файл новее нашего формата)
 * → прежние at/site/banners остаются, только error; повтор — на следующем
 * тике (кеш так и остаётся старым). Домен из файла — api.setPreferred:
 * после удачного забора и при каждом старте воркера из кеша (память
 * модуля api.js сон стирает). Адрес файла и тексты баннеров в консоль не
 * попадают — только числа.
 *
 * Память воркера (3.2, допустимо): fetchingRemote — забор в полёте, чтобы
 * старт и будильник, совпав по времени, делили один заход; после сна пуст.
 */

let fetchingRemote = null;

/** Будильник файла сообщений: заведён всегда; уже заведённый не перезаводится (период не сдвигать). */
async function configAlarm() {
  const existing = await chrome.alarms.get(constants.ALARMS.CONFIG);
  if (existing) return;
  await chrome.alarms.create(constants.ALARMS.CONFIG, { periodInMinutes: constants.CONFIG_PERIOD_MIN });
  console.log(`[pxs] будильник файла сообщений заведён, период ${constants.CONFIG_PERIOD_MIN} мин`);
}

/**
 * Файл сообщений при старте браузера и при установке или обновлении
 * расширения: будильник и, при кеше старше CONFIG_TTL_MIN или без кеша, забор.
 * Только здесь, а не при каждом пробуждении воркера — при недоступном
 * сервере запрос уходил бы при каждом пробуждении (как у аккаунта).
 *
 * @param {{result: string}} prep итог prepareStorage()
 * @param {string} reason
 */
async function configAtStart(prep, reason) {
  if (!prepared(prep)) return;
  await configAlarm();
  await fetchRemoteIfStale(reason);
}

/**
 * Забор только при кеше старше CONFIG_TTL_MIN или без кеша (at 0 — ещё ни
 * одного удачного забора); свежий кеш — строка в консоль и ничего.
 *
 * @param {string} reason
 * @returns {Promise<{ok: boolean, error?: string, count?: number, skipped?: boolean}>}
 */
async function fetchRemoteIfStale(reason) {
  const cur = await state.getRemote();
  const age = cur && cur.at > 0 ? Date.now() - cur.at : Infinity;
  if (age <= constants.CONFIG_TTL_MIN * 60000) {
    console.log(`[pxs] файл сообщений (${reason}): кеш свежий, ${Math.round(age / 60000)} мин — забор по будильнику`);
    return { ok: true, skipped: true };
  }
  return fetchRemote(reason);
}

/**
 * Забрать, разобрать, записать кеш и поставить домен из файла первым в
 * очередь запросов. Старт и будильник, совпав по времени, делят один
 * заход — и всё.
 *
 * @param {string} reason 'startup' | 'install' | 'update' | 'alarm'
 * @returns {Promise<{ok: boolean, error?: string, count?: number}>}
 */
function fetchRemote(reason) {
  if (!fetchingRemote) {
    fetchingRemote = runFetchRemote(reason).finally(() => {
      fetchingRemote = null;
    });
  }
  return fetchingRemote;
}

async function runFetchRemote(reason) {
  const got = await api.fetchConfig();
  if (got.ok) {
    await state.setRemote({ at: got.at, site: got.site, banners: got.banners, error: null });
    api.setPreferred(got.site);
    console.log(`[pxs] файл сообщений (${reason}): получен, сообщений ${got.banners.length}${got.site ? `, домен ${got.site}` : ''}`);
    return { ok: true, count: got.banners.length };
  }
  const previous = await state.getRemote();
  await state.setRemote({
    at: previous ? previous.at : 0,
    site: previous ? previous.site : '',
    banners: previous ? previous.banners : [],
    error: got.error,
  });
  console.warn(`[pxs] файл сообщений (${reason}): отказ (${got.error}) — прежний кеш оставлен`);
  return { ok: false, error: got.error };
}

/** При старте воркера — домен из кеша первым в очередь запросов api.js (память модуля сон стирает). */
function initRemote() {
  return state.getRemote()
    .then((cur) => {
      if (cur && cur.site) api.setPreferred(cur.site);
    })
    .catch((err) => {
      console.error('[pxs] файл сообщений: кеш не прочитался:', err);
    });
}

/* ── самолечение при «Неверный логин или пароль» (6.1) ─────────────────
 * Пароль у прокси из аккаунта сменился на сервере или испорчен рукой:
 * прокси отказывает, обработчик авторизации (auth.js) отменяет запрос и
 * ставит lastError 'auth'. До 6.1 расширение краснело и ждало будильника
 * до шести часов. Теперь: заметить отказ, взять пароль из аккаунта,
 * переподключиться — само, за секунды.
 *
 * Ограничение этапа 6: запрос к аккаунту не может идти через сломанный
 * прокси (его отменит тот же обработчик). Поэтому на время лечения ставится
 * ВРЕМЕННАЯ настройка — существующий шаблон PAC с чёрным списком из хостов
 * сайта аккаунта (SITE_HOSTS: основной и зеркало, оба напрямую), всё
 * остальное на тот же прокси (и падает, как падало). Настоящий IP наружу
 * не уходит: у прокси в скрипте нет хвоста с прямым соединением, mandatory
 * стоит. Обычная настройка возвращается ВСЕГДА, в finally, чтобы временная
 * не осталась.
 *
 * Лечится только прокси из аккаунта (src 'pxs') при привязанном ключе и
 * живом кеше аккаунта; ручному прокси взять пароль неоткуда. Не чаще раза
 * в HEAL_COOLDOWN_MIN на один прокси. Всё лечение — ОДНА работа в очереди
 * применений: enable / switch / disable и повторное применение по подписке
 * дождутся её конца.
 *
 * Два спусковых крючка, оба сходятся в maybeHeal():
 *  1. подписка на state — пришёл lastError 'auth' (переход из null);
 *  2. запрос пароля от прокси (chrome.webRequest.onAuthRequired без
 *     блокировки, наблюдение) при УЖЕ красном герое. Нужен потому, что
 *     повторные отказы состояния не меняют: state.js не пишет то же
 *     значение, и события нет. Без него после неудачного лечения (сервер
 *     недоступен, тот же пароль) второй попытки «через десять минут» не
 *     было бы, пока человек не тронет прокси сам.
 * Уведомление — с 7Г: удачное лечение пишет событие 'healed' в ключ notifs
 * (noteEvent — карточка панели «пароль обновлён из аккаунта»); системного
 * уведомления у лечения нет (оно одно — при переключении при обрыве). Без
 * правок окон, без таймеров: cooldown — метка времени в памяти воркера,
 * сравнение при событии.
 */

/* Лечение в работе или в очереди — второе не заводится. Память воркера. */
let healing = false;

/*
 * Время последней попытки по идентификатору прокси. Память воркера: сон её
 * стирает, и после пробуждения лечение разрешено заново — допустимо
 * (решение 6.1), хранилищем ради этого не пользуемся.
 */
const healAt = new Map();

/*
 * Запоздавшие отказы (решение сессии). Пока шёл запрос к аккаунту, вкладки
 * продолжали ходить через прокси со старым паролем: запрос, которому
 * auth.js дважды ответил старым паролем ДО записи нового, получает третий
 * запрос пароля уже ПОСЛЕ неё — и auth.js честно ставит 'auth', хотя пароль
 * в записи уже верный и настройка возвращена. Такой отказ догоняет нас в
 * пределах одного оборота до прокси. Поэтому после удачного лечения отказ
 * по тому же прокси в течение HEAL_SETTLE_MS снимается, а не считается
 * новым. Настоящий повторный отказ придёт следующим запросом уже после
 * окна и останется. Память воркера, как и всё здесь.
 */
const HEAL_SETTLE_MS = 5000;
let healedId = '';
let healedAt = 0;

/*
 * Быстрый отказ сети на запросе к аккаунту (решение сессии по находке
 * человека 10.09: «обновление не удалось (net)» при доступном сервере).
 * Временная настройка уже принята браузером, но сетевой слой мог ещё не
 * перейти на неё — первый запрос уходит по прежней настройке, через
 * сломанный прокси, и его отменяет auth.js за доли секунды. Такой отказ
 * повторяется один раз; настоящая недоступность сервера (ожидание ответа
 * до предела) второй попытки не получает — очередь применений не должна
 * стоять вдвое дольше.
 */
const HEAL_FAST_FAIL_MS = 5000;

/** Отказ пришёл в окно после удачного лечения — со старым паролем, снимаем. */
function settle() {
  return state.setLastError(null).catch((err) => {
    console.error('[pxs] самолечение: не удалось снять запоздавший отказ:', err);
  });
}

/**
 * Проверить условия и, если все сошлись, поставить лечение в очередь.
 * Иначе — ничего, как до 6.1.
 *
 * Условия: прокси включён; активный найден и он из аккаунта; ключ привязан;
 * кеш аккаунта есть и не помечен отказом ключа; для этого прокси прошло
 * больше HEAL_COOLDOWN_MIN с прошлой попытки; лечение сейчас не идёт.
 *
 * @param {Object} st состояние (уже в готовой форме)
 * @returns {Promise<void>}
 */
function maybeHeal(st) {
  if (healing || !st || !st.enabled || !st.activeProxyId) return Promise.resolve();
  const last = healAt.get(st.activeProxyId) || 0;
  if (Date.now() - last < constants.HEAL_COOLDOWN_MIN * 60000) return Promise.resolve();

  // Флаг ставится до чтений: два отказа подряд (две вкладки) дали бы два лечения.
  healing = true;
  return (async () => {
    try {
      const [list, settings, account] = await Promise.all([
        state.getProxies(), state.getSettings(), state.getAccount(),
      ]);
      const found = list.find((p) => p && p.id === st.activeProxyId);
      if (!found || found.src !== constants.SRC.PXS) return;
      if (settings.apiKey === '' || !account || account.error) return;
      await inLine(() => heal(found));
    } finally {
      healing = false;
    }
  })();
}

/**
 * Само лечение — внутри очереди применений.
 *
 * Состояние перечитывается первым делом: пока работа ждала очередь, впереди
 * могли стоять «выключить» или «переключить» — тогда лечить нечего, и
 * временная настройка включила бы прокси обратно вопреки человеку.
 *
 *  а) временная настройка: тот же прокси, чёрный список из хостов сайта
 *     аккаунта (applyProxy при этом, как любое применение, снимает
 *     lastError — пока лечим, герой не красный);
 *  б) refresh('heal') — обновит кеш и перепишет пароль в записи, если в
 *     аккаунте он другой (updateAdded). Обновление, уже идущее в этот
 *     момент (будильник или кнопка совпали с отказом), ушло через
 *     сломанный прокси и обречено — его дожидаемся и запрашиваем заново,
 *     а не делим его исход; быстрый отказ сети — ещё один запрос, один раз;
 *  в) в finally — перечитать запись и вернуть обычную настройку: режим и
 *     списки соберутся по settings, креды перечитаются;
 *  г) исход: логин или пароль в записи изменились → переподключились
 *     (и запоздавший отказ со старым паролем, если успел, снят);
 *     не изменились → lastError 'auth' обратно; обновление не удалось →
 *     то же, с причиной.
 *
 * @param {Object} found запись прокси на момент отказа
 */
async function heal(found) {
  const st = await state.getState();
  if (!st.enabled || st.activeProxyId !== found.id) {
    console.log('[pxs] самолечение отменено: прокси выключен или сменён, пока ждали очередь');
    return;
  }

  healAt.set(found.id, Date.now());
  console.log('[pxs] самолечение: прокси отказал на логине и пароле — берём пароль из аккаунта, сайт аккаунта на это время напрямую');

  let res = { ok: false, error: 'failed' };
  let fresh = found;
  try {
    const tmp = await proxy.applyProxy(found, null, {
      lists: { listMode: 'black', domains: constants.SITE_HOSTS, skipped: 0 },
    });
    if (!tmp.ok) throw new Error(`временная настройка не применилась — ${tmp.message}`);
    if (refreshing) await refreshing.catch(() => {});
    const started = Date.now();
    res = await refresh('heal');
    if (!res.ok && res.error === 'net' && Date.now() - started < HEAL_FAST_FAIL_MS) {
      console.warn('[pxs] самолечение: запрос к аккаунту не дошёл — вторая попытка');
      res = await refresh('heal');
    }
  } catch (err) {
    console.error('[pxs] самолечение: ошибка по дороге к аккаунту —', err);
  } finally {
    const list = await state.getProxies();
    fresh = list.find((p) => p && p.id === found.id) || found;
    const back = await proxy.applyProxy(fresh, () => auth.reloadCreds());
    if (!back.ok) console.warn(`[pxs] самолечение: обычная настройка не вернулась — ${back.message}`);
  }

  if (fresh.login !== found.login || fresh.pass !== found.pass) {
    // Отказы, догнавшие нас со старым паролем, пока возвращалась настройка, — не в счёт.
    healedId = found.id;
    healedAt = Date.now();
    await settle();
    console.log('[pxs] самолечение: пароль обновлён из аккаунта, переподключились');
    // 7Г: карточка «Пароль у … обновлён из аккаунта» в панели — событие, из данных этого не восстановить.
    await noteEvent('healed', { id: found.id, ip: found.ip });
    return;
  }
  if (res.ok) {
    await state.setLastError('auth');
    console.warn(fresh.gone
      ? '[pxs] самолечение: прокси нет в аккаунте — ошибка остаётся'
      : '[pxs] самолечение: в аккаунте тот же пароль — ошибка остаётся');
    return;
  }
  await state.setLastError('auth');
  console.warn(`[pxs] самолечение: обновление не удалось (${res.error}) — ошибка остаётся`);
}

/*
 * Второй крючок (решение человека 10.09, В1): прокси снова спрашивает
 * пароль, а герой уже красный. Наблюдение, не блокировка: на запрос
 * пароля этот слушатель не отвечает никогда — отвечает только auth.js.
 * Слушатель на верхнем уровне, синхронный, ничего не возвращает; чужой
 * сайт со своим паролем (isProxy не true) — не наше дело. Чтение состояния
 * — одно на запрос пароля от прокси, и только пока лечение не идёт:
 * при рабочем пароле прокси спрашивает его раз за сеанс.
 */
chrome.webRequest.onAuthRequired.addListener((details) => {
  if (!details || details.isProxy !== true || healing) return;
  state.getState()
    .then((st) => (st.lastError === 'auth' ? maybeHeal(st) : undefined))
    .catch((err) => {
      console.error('[pxs] самолечение по запросу пароля упало:', err);
    });
}, { urls: ['<all_urls>'] });

/* ── обрыв: прокси не отвечает (7Б, 7.6) ──────────────────────────────
 * До 7Б мёртвый прокси выглядел как «включено» — и это было правдой:
 * настройка применена, просто прокси не отвечает; человек видел страницу
 * ошибки браузера. Теперь обрыв замечается по настоящему трафику:
 * chrome.webRequest.onErrorOccurred приносит ошибку каждого запроса
 * вместе с его адресом (chrome.proxy.onProxyError адреса не несёт и
 * по-прежнему только пишет в консоль).
 *
 * Правило (мастер-промт 10, план 7.6, решения человека 11.09): за
 * DEAD_WINDOW_MS (минута — В7-а, длиннее десяти секунд мастер-промта:
 * руками сайты открывают медленнее) пришло DEAD_ERRORS ошибок прокси из
 * DEAD_ERROR_CODES на стольких же РАЗНЫХ хостах → lastError 'dead'
 * (герой красный, «Не отвечает»). Разные хосты — потому что один адрес
 * падает и на исправном прокси (IPv6-проба сайта). Считаются только
 * ошибки «до прокси не достучаться» — ERR_TUNNEL_CONNECTION_FAILED не в
 * счёт (В3-а): так исправный прокси отвечает на сайт, недоступный из его
 * страны; ERR_TIMED_OUT не в счёт (В8-а): молчащий прокси от молчащего
 * сайта не отличить — известное ограничение, такой прокси человек
 * переключает сам. Пока браузер сообщает «сеть отключена»
 * (navigator.onLine false), ошибки не считаются и не копятся (В4): без
 * интернета падает всё, и прокси тут ни при чём. Контрольного запроса
 * напрямую перед объявлением мёртвым нет (решение человека 11.09):
 * «напрямую» при включённом прокси возможно только временной настройкой,
 * а в регионах без доступа к сайту аккаунта он падал бы всегда — и прокси
 * не объявлялся бы мёртвым никогда.
 *
 * Ошибка 'auth' не перебивается ('dead' ставится только из null);
 * повторно 'dead' не ставится — обрыв один, пока прокси не применили
 * заново: любое применение снимает lastError (как и прежде), отдельного
 * «ожил» нет. Счётчик — карта «хост → время ошибки» в памяти воркера;
 * сон её стирает, и обрыв, начавшийся до сна, досчитается заново —
 * допустимо, записано (3.2). Сбрасывается при смене enabled,
 * activeProxyId или lastError в state (после включения, переключения,
 * выключения и самого 'dead'; уточнение 7В — запись результата проверки
 * счётчик не трогает): ошибки прежнего прокси новому не засчитываются.
 *
 * Переключение при обрыве (тумблер settings.failover) — одна работа в
 * очереди применений inLine, как команда switch: следующий по списку
 * после активного, по кругу, минуя «нет в аккаунте» (gone), истёкшие и
 * те, что сами умирали за последние FAILOVER_COOLDOWN_MIN минут (карта
 * deadAt в памяти воркера — чтобы два мёртвых прокси не переключались
 * друг на друга по кругу). Нашли — enableProxy, как при switch; не
 * нашли — остаёмся с 'dead'. Одно системное уведомление на один обрыв
 * (единственное системное на этапе; кнопки и ссылки в нём — 7Г): либо
 * «переключились A → B», либо «рабочего прокси не нашлось». Окна про
 * переключение узнают по подписке, как о смене из соседнего окна.
 */

/* Ошибки прокси за окно DEAD_WINDOW_MS: хост → время последней. Память воркера. */
const deadHits = new Map();
/* 7Ж (находка человека 18.09): при белом списке через прокси идут только
   перечисленные сайты, и «три разных хоста» одному сайту не набрать никогда
   — мёртвый прокси оставался «подключённым», сколько ни обновляй страницу.
   Поэтому в белом режиме считаются три отказа за то же окно на любых хостах,
   хоть на одном: код ERR_PROXY_CONNECTION_FAILED от сайта не зависит
   (DECISIONS 11.09, В7). Флаг режима — память воркера, читается при старте
   и по подписке на settings; пока не прочитан — правило чёрного режима. */
let whiteMode = false;
let deadSeq = 0;

/*
 * Тишина после записи состояния (DEAD_QUIET_MS): до этого момента ошибки
 * не считаются. Запросы, начатые ещё через прежний прокси, падают уже
 * после переключения — без тишины три таких запоздавших отказа объявили
 * бы мёртвым свежевключённый прокси, а при автопереключении — и следующий
 * за ним. Отказ соединения приходит за доли секунды, пяти секунд хватает;
 * обрыв нового прокси досчитается после них. Память воркера, как и
 * счётчик.
 */
let quietUntil = 0;

/* Обрыв разбирается (чтение состояния, запись, переключение) — второй не заводится. */
let dying = false;

/* Когда какой прокси объявлялся мёртвым: id → мс. Память воркера (см. FAILOVER_COOLDOWN_MIN). */
const deadAt = new Map();

/* Одно уведомление на один обрыв; новое заменяет прежнее, а не встаёт рядом. */
const FAILOVER_NOTIFICATION = 'pxs-failover';

/** Ошибка из набора обрыва — строка браузера приходит с префиксом «net::». */
function isDeadError(error) {
  return typeof error === 'string' && constants.DEAD_ERROR_CODES.includes(error.replace(/^net::/, ''));
}

/** Хост запроса, если это http или https; иначе пустая строка. */
function requestHost(url) {
  if (typeof url !== 'string' || !/^https?:/i.test(url)) return '';
  try {
    return new URL(url).hostname;
  } catch (err) {
    return '';
  }
}

/**
 * Записать ошибку и, если набралось, разобрать обрыв. Синхронно: зовётся
 * из слушателя. Разбор — одна работа, пока идёт, новые ошибки только
 * считаются (и после него счётчик всё равно пуст).
 *
 * @param {string} host
 */
function noteDeadError(host) {
  const now = Date.now();
  for (const [h, at] of deadHits) {
    if (now - at > constants.DEAD_WINDOW_MS) deadHits.delete(h);
  }
  deadHits.set(whiteMode ? `${host}#${++deadSeq}` : host, now);   // белый список: каждый отказ — своя запись
  if (deadHits.size < constants.DEAD_ERRORS) return;
  startDead(`${constants.DEAD_ERRORS} ошибки прокси за ${constants.DEAD_WINDOW_MS / 1000} с ${whiteMode ? '(белый список)' : 'на разных хостах'}`);
}

/**
 * Запустить разбор обрыва одной работой (флаг dying): пока идёт, новые
 * ошибки только считаются. Синхронно: зовётся из слушателя. Два входа —
 * порог по трафику (7Б) и отказ соединения на запросе проверки (7В).
 *
 * @param {string} why причина для строки в консоли
 * @param {string} [forId] прокси, о котором отказ (7В) — не тот же, что
 *   активный, значит его уже сменили, и отказ не про него
 */
function startDead(why, forId) {
  if (dying) return;
  dying = true;
  markDead(why, forId)
    .catch((err) => {
      console.error('[pxs] обрыв не разобран:', err);
    })
    .finally(() => {
      dying = false;
    });
}

/* ── 2.6 · лечение протокола после обрыва ───────────────────────────────
 * У записи из строки без схемы тип угадан по порту (proxytype.js; в списке
 * такой тип помечен звёздочкой). Догадка бывает неверной — и тогда всё
 * выглядит как мёртвый прокси: ни один запрос не проходит, фон пишет
 * 'dead', человек читает «Нет ответа», хотя прокси жив и просто говорит на
 * другой схеме.
 *
 * Что делаем: один раз на адрес проверяем протокол живой пробой
 * (typecheck.js — четыре схемы по http, 2 с на схему) и, если ответила
 * другая, записываем её в строку и подключаемся заново. Пометка
 * typeVerified снимает догадку: звёздочка в списке исчезает.
 *
 * Границы:
 *  - только при угаданном и ещё не подтверждённом типе;
 *  - только пока включено и активен тот же прокси; повод — либо 'dead'
 *    (обрыв), либо проверка при подключении, через которую не прошёл ни
 *    один запрос (fromProbe): и то и другое значит «трафика нет»;
 *  - один раз на адрес за жизнь воркера (healTried) и не больше HEAL_MAX
 *    адресов: адрес, на который не ответила ни одна схема, второй раз
 *    проверять нечего;
 *  - идёт ДО переключения при обрыве: если дело было в протоколе, менять
 *    прокси незачем;
 *  - любой отказ (ни одна схема не ответила, прокси сменили, настройка не
 *    применилась) — просто false: 'dead' остаётся, работает обычный путь.
 */
const healTried = new Set();
const HEAL_MAX = 8;

async function healType(id, opts) {
  const fromProbe = !!(opts && opts.fromProbe);
  if (!id || healTried.size >= HEAL_MAX) return false;
  const st = await state.getState();
  if (!st.enabled || st.activeProxyId !== id) return false;
  /* Поводы не смешиваются: из обрыва — только по 'dead'; из проверки — только
     пока ошибки нет (иначе её уже разбирает свой путь: 'auth', 'dead'). */
  if (fromProbe ? st.lastError !== null : st.lastError !== 'dead') return false;
  const list = await state.getProxies();
  const p = list.find((x) => x && x.id === id);
  if (!p || p.typeGuess !== true || p.typeVerified === true) return false;
  const key = `${String(p.ip).toLowerCase()}:${p.port}`;
  if (healTried.has(key)) return false;
  healTried.add(key);

  console.log('[pxs] лечение протокола: тип был угадан — проверяю, не другая ли схема');
  const res = await typecheck.checkType(
    { ip: p.ip, port: p.port, login: p.login || '', pass: p.pass || '', type: p.type },
    { fresh: true, whileDead: true },
  );
  if (!res.ok) {
    console.log(`[pxs] лечение протокола: ни одна схема не ответила (${res.error}) — ошибка остаётся`);
    return false;
  }
  const found = normType(res.type);
  if (found === normType(p.type)) {
    console.log(`[pxs] лечение протокола: догадка верна (${found}) — дело не в протоколе, ошибка остаётся`);
    return false;
  }

  /* Запись перечитывается: пока шла проба, человек мог её удалить или
     сменить пароль в соседнем окне. */
  const cur = await state.getProxies();
  if (!cur.some((x) => x && x.id === id)) return false;
  const upd = { ...p, type: found, typeVerified: true };
  delete upd.typeGuess;
  await state.setProxies(cur.map((x) => (x.id === id ? upd : x)));

  const after = await state.getState();
  if (!after.enabled || after.activeProxyId !== id) return false;
  const back = await enableProxy(id);   // applyProxy без keepError — 'dead' снимается
  if (!back.ok) {
    console.warn(`[pxs] лечение протокола: это ${found}, но настройка не применилась (${back.error})`);
    return false;
  }

  console.log(`[pxs] лечение протокола: протокол — ${found}, переподключились`);
  await noteEvent('healed', { id, ip: p.ip, type: found });
  probeAfter('healType');   // подтверждение новой схемы, как после команды окна
  return true;
}

/**
 * Порог набран (или отказ на запросе проверки): проверить состояние,
 * поставить 'dead', при включённом тумблере — поставить переключение в
 * очередь.
 *
 * @param {string} why
 * @param {string} [forId]
 */
async function markDead(why, forId) {
  const st = await state.getState();
  deadHits.clear();
  if (!st.enabled || st.lastError !== null) return;   // выключен, уже 'dead', либо 'auth' — не перебиваем
  if (forId !== undefined && st.activeProxyId !== forId) return;   // 7В: прокси сменили, пока шёл запрос проверки — отказ не про новый

  await state.setLastError('dead');
  console.warn(`[pxs] обрыв: ${why} — прокси не отвечает, записано 'dead'`);

  const settings = await state.getSettings();
  /* 2.6: прежде чем искать замену — поправить возможную ошибку протокола.
     Прокси с угаданным по порту типом, который говорит на другой схеме,
     выглядит ровно как мёртвый. Лечение возвращает true, если тип нашёлся
     и подключение поднялось: тогда 'dead' уже снят, и переключаться не
     нужно. Внутри очереди (путь переключения при обрыве) — без нового
     inLine, иначе очередь ждала бы саму себя. */
  const healNow = () => healType(st.activeProxyId);
  if (await (inQueue ? healNow() : inLine(healNow))) return;

  if (settings.failover !== true) return;
  // Переключение ставится в очередь и НЕ ждётся здесь (третья выдача 7В):
  // после переключения идёт проверка нового прокси, и её отказ соединения
  // должен разбираться своим startDead, пока флаг dying уже снят — иначе
  // цепочка «мёртв → следующий мёртв → следующий» обрывалась бы на первом шаге.
  inLine(() => failover(st.activeProxyId)).catch((err) => {
    console.error('[pxs] переключение при обрыве упало:', err);
  });
}

/**
 * Переключение при обрыве — внутри очереди применений. Состояние
 * перечитывается первым делом: пока работа ждала очередь, впереди могли
 * стоять «выключить» или «переключить» от человека.
 *
 * @param {string} fromId прокси, объявленный мёртвым
 */
async function failover(fromId) {
  const st = await state.getState();
  if (!st.enabled || st.activeProxyId !== fromId || st.lastError !== 'dead') {
    console.log('[pxs] переключение при обрыве отменено: прокси выключен или сменён, пока ждали очередь');
    return;
  }
  const [list, settings] = await Promise.all([state.getProxies(), state.getSettings()]);
  if (settings.failover !== true) return;

  const now = Date.now();
  deadAt.set(fromId, now);
  const from = list.find((p) => p && p.id === fromId);
  const idx = list.findIndex((p) => p && p.id === fromId);

  const candidates = [];
  for (let k = 1; k < list.length; k++) {
    const p = list[(idx + k) % list.length];
    if (!p || p.id === fromId || p.gone === true || isExpired(p)) continue;
    const died = deadAt.get(p.id);
    if (died && now - died < constants.FAILOVER_COOLDOWN_MIN * 60000) continue;
    candidates.push(p);
  }

  for (const p of candidates) {
    const res = await enableProxy(p.id);
    if (res.ok) {
      console.log(`[pxs] переключение при обрыве: ${from ? hostPort(from) : fromId} → ${hostPort(p)}`);
      await notify(msg('nFailoverT'), msg('nFailoverS', [from ? hostPort(from) : '?', hostPort(p)]));
      // 7Г: та же карточка в панели уведомлений — событие рядом с уведомлением,
      // и только здесь: при выключенном тумблере переключения ни того, ни другого
      // (ошибку показывают окна и красная метка на значке).
      await noteEvent('lost', { id: fromId, ip: from ? from.ip : '?', newIp: p.ip });
      // 7В (решение человека 11.09, В3 — третья выдача): после каждого
      // переключения — проверка при подключении, как после команды окна:
      // мёртвый следующий даст 'dead' и следующее переключение, цепочка идёт
      // до живого или «замены не нашлось» (умиравшие за FAILOVER_COOLDOWN_MIN
      // не берутся — не больше одного круга). Тумблер проверки выключен —
      // проверки нет, следующий обрыв ловит трафик по правилу 7Б.
      await probeAfter('failover');
      return;
    }
    if (res.error === 'controlled_by_other_extensions' || res.error === 'not_controllable') {
      console.warn(`[pxs] переключение при обрыве: управление не у нас (${res.error}) — остаёмся`);
      return;
    }
    console.warn(`[pxs] переключение при обрыве: ${hostPort(p)} не включился (${res.error}) — пробуем следующий`);
  }

  console.warn(`[pxs] переключение при обрыве: замены в списке не нашлось (кандидатов ${candidates.length}) — остаёмся с 'dead'`);
  await notify(msg('nFailoverNoneT'), msg('nFailoverNoneS'));
  // 7Г: карточка «не отвечает» без замены — без newIp.
  await noteEvent('lost', { id: fromId, ip: from ? from.ip : '?' });
}

/**
 * Системное уведомление: заголовок, текст, цветной значок расширения
 * (путь полным адресом через getURL — как у базы значка в badge.js).
 * Без кнопок и ссылок — и они не появятся (решение 15.09): хвост 7Б
 * закрыт карточкой 'lost' в панели уведомлений попапа; переход по клику
 * на само уведомление — если человек захочет, 7Е. Отказ уведомления
 * обрыв не роняет. Единственное системное уведомление в проекте.
 *
 * @param {string} title
 * @param {string} message
 */
async function notify(title, message) {
  try {
    await chrome.notifications.create(FAILOVER_NOTIFICATION, {
      type: 'basic',
      iconUrl: chrome.runtime.getURL(constants.ICONS.on[48]),
      title,
      message,
    });
  } catch (err) {
    console.warn('[pxs] уведомление не показано:', err);
  }
}

/* ── проверка при подключении (7В, 7.2) ──────────────────────────────
 * Решение 29.08: индикатора качества нет, результат проверки — только в
 * диагностику для поддержки. Пересмотр 11.09 (DECISIONS v2.30) в одной
 * части: запрос проверки — ПЕРВЫЙ запрос через новый прокси, и по нему
 * приходят однозначные признаки, которые раньше ждали настоящего
 * трафика: неверный пароль ставит 'auth' сам обработчик авторизации
 * (auth.js) на этих же запросах — здесь ничего добавлять не надо, только
 * не мешать; отказ соединения с прокси (код из DEAD_ERROR_CODES в
 * onErrorOccurred на любом из запросов проверки) не зависит от сайта →
 * 'dead' сразу, без ожидания трёх хостов, дальше тот же путь, что при
 * обрыве (markDead → переключение при тумблере, уведомление). Третья и
 * пятая выдачи (решения человека 11.09, В2-а и по находке на первом же
 * аккаунте): запросов пять, параллельно — два хоста SITE_HOSTS и три
 * чужих адреса проверки связи PROBE_HOSTS; ответил хоть один чем угодно —
 * жив, «N мс»; ответили только чужие — жив, но сайт через прокси не виден
 * (probeSiteDown, строка в диагностике); только ошибки живого прокси
 * (туннель, сброс) — жив, «не прошла»; тишина на всех пяти за наш предел
 * — 'dead' тем же путём (probe.js отвечает silent: true). Остаточный
 * риск: прокси, через который молчат все пять адресов, объявляется
 * мёртвым.
 *
 * Зовётся после удачных enable и switch от окна (вне очереди применений
 * — это не настройка браузера; ответ окну ждёт только пометку probing),
 * после каждого удачного переключения при обрыве (В3, третья выдача) —
 * цепочка переключений идёт до живого прокси или «замены не нашлось» —
 * и при старте браузера после сверки, если прокси остался включённым
 * (probeAtStart, четвёртая выдача).
 * Тумблер settings.verify выключен — не зовётся и lastProbe* не трогает;
 * немедленного результата тогда нет — только по трафику (7Б). При белом
 * списке (7Ж, находка человека 18.09 — отменяет «не измерялся» решения
 * 11.09, В1-а) проверка идёт только по трём чужим адресам связи: скрипт
 * PAC в белом режиме ведёт их через прокси (CHECK_HOSTS), а хосты сайта
 * идут по списку, напрямую, и о прокси не сказали бы ничего; строка про
 * недоступный сайт (probeSiteDown) при белом списке не измеряется.
 *
 * Результат засчитывается, только если activeProxyId к моменту ответа
 * тот же (аудит 3Б.4) — иначе отклик прежнего прокси лёг бы к новому.
 *
 * Пометка state.probing (вторая выдача 7В, решение человека 11.09; поле
 * в схеме STATE с его согласия, schemaVersion 1): true пишется до ответа
 * окну, false — с результатом (probeResult) по любому исходу, а также
 * при выключении, аварийном сбросе и сверке при старте (probeOff) —
 * застрявшая после гашения воркера пометка снимается стартом. Окна при
 * enabled и probing держат коннектор в состоянии подключения с подписью
 * «Подключение» (В1 третьей выдачи), по снятию — «Подключено» с
 * пристыковкой либо красный по lastError. Две записи состояния на
 * подключение счётчик обрыва и тишину не трогают (см. подписку на state
 * ниже).
 *
 * Память воркера (допустимо, записать в мастер-промт 3.2): probing —
 * запрос проверки в полёте { id, gen, ctrl, doneAt }; по нему слушатель
 * onErrorOccurred узнаёт свой запрос (вместе с адресом PROBE_URL и методом
 * HEAD) и на него не распространяет тишину DEAD_QUIET_MS — он свой, не
 * запоздавший. В полёте — не больше одного: новый запрос проверки
 * отменяет прежний (ctrl.abort), иначе отказ соединения с прежним
 * прокси, пришедший после смены, достался бы новому; отменённый запрос
 * заканчивается кодом отмены, а не отказа, и обрывом не считается.
 * Событие об ошибке запроса и отказ самого fetch приходят в воркер
 * разными путями, и порядок между ними браузер не обещает: если забыть
 * запрос сразу по отказу fetch, событие, пришедшее следом, сочли бы чужим
 * и потеряли бы в тишине. Поэтому запрос считается «своим» ещё
 * PROBE_LATE_MS после того, как fetch закончился; чужой HEAD к тому же
 * адресу в это же мгновение — не про нас, вкладки запрашивают значок
 * сайта методом GET. Сон стирает — после пробуждения запроса в полёте
 * нет, это правда.
 */

let probing = null;
let probeGen = 0;
const PROBE_LATE_MS = 2000;

/**
 * Единственное место записи lastProbeAt / lastProbeMs (0/0 — «не
 * измерялся») и probeSiteDown (пятая выдача: ответили только чужие
 * адреса — сайт через прокси не виден); вместе с результатом снимается
 * пометка probing — любой исход проверки её снимает (вторая выдача 7В).
 */
function probeResult(at, ms, siteDown) {
  return state.patchState({ lastProbeAt: at, lastProbeMs: ms, probeSiteDown: siteDown === true, probing: false });
}

/** Снять пометку probing: выключение, аварийный сброс, сверка при старте. Стоит false — записи нет. */
function probeOff() {
  return state.patchState({ probing: false });
}

/** Свой запрос проверки (любой из пяти) — в полёте или только что закончился: по адресу, методу и памяти воркера. */
function isProbeRequest(details) {
  if (probing === null || !probe.PROBE_REQUESTS.some((r) => r.url === details.url && r.method === details.method)) return false;
  return probing.doneAt === 0 || Date.now() - probing.doneAt < PROBE_LATE_MS;
}

/**
 * Проверка после команды окна в два шага: startProbe — решение и пометка
 * probing в state (ответ окну ждёт только её), finishProbe — сам запрос
 * и результат, уже после ответа. Ошибок наружу не отдаёт.
 *
 * @returns {Promise<void>} разрешается, когда пометка записана (или проверки не будет)
 */
function probeAfter(cmd) {
  return startProbe(cmd)
    .then((job) => {
      if (!job) return;
      finishProbe(job).catch((err) => {
        console.error('[pxs] проверка при подключении упала:', err);
      });
    })
    .catch((err) => {
      console.error('[pxs] проверка при подключении не запустилась:', err);
    });
}

/* ── 2.6.1 · ДОКАЗАТЕЛЬСТВО ВЫХОДА ────────────────────────────────────────
 * «Онлайн» у нас означает «настройка применена и проверка прошла», но человек
 * смотрит не на настройку, а на сайт: у него в строке адреса всё ещё его
 * собственный город, и он делает вывод «IP не меняется, расширение не
 * работает». Правда проста и проверяема: страница была открыта ДО включения.
 * Поэтому сразу после включения фон спрашивает внешнюю службу, какой адрес
 * она видит, и кладёт ответ в state (exit*). Окно показывает его строкой под
 * героем — «Выход: 45.9.41.177 · Германия» и кнопку «Обновить страницу».
 *
 * Заодно запоминается свой адрес (directIp) — он снимается, когда прокси
 * выключен. Если выходной адрес совпал со своим при включённом прокси, окно
 * честно говорит «адрес тот же, что у вас» — это единственный случай, когда
 * у человека есть повод искать ошибку.
 *
 * Ответа окну проверка не задерживает: она идёт следом и приходит подпиской
 * на state. Таймаут 6 с, службы те же, что у «Проверить IP» в попапе; отказ
 * ничего не стирает — прежний ответ остаётся со своей датой.
 */
const EXIT_URLS = Object.freeze([
  'https://ipwho.is/?fields=success,ip,country_code,city',
  'https://api.ipify.org?format=json',
]);
const EXIT_TIMEOUT_MS = 6000;
/** Хвост проверки выхода: второй заход не начинается, пока идёт первый. */
let exitTail = Promise.resolve();

async function askExit() {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), EXIT_TIMEOUT_MS);
  try {
    for (const url of EXIT_URLS) {
      try {
        const res = await fetch(url, { cache: 'no-store', credentials: 'omit', signal: ctrl.signal });
        if (!res.ok) continue;
        const j = await res.json();
        const ip = String((j && (j.ip || j.query)) || '');
        if (!isIPHost(ip)) continue;
        const cc = typeof j.country_code === 'string' && /^[A-Za-z]{2}$/.test(j.country_code) ? j.country_code.toUpperCase() : '';
        const city = typeof j.city === 'string' ? j.city.replace(/\s+/g, ' ').trim().slice(0, 40) : '';
        return { ip, cc, city };
      } catch (err) {
        if (ctrl.signal.aborted) return null;
      }
    }
    return null;
  } finally {
    clearTimeout(timer);
  }
}

/**
 * Спросить, какой адрес видят сайты, и записать его в состояние.
 * @param {'connect'|'switch'|'disable'|'manual'} why
 * @returns {Promise<{ip: string, cc: string, city: string}|null>}
 */
function proveExit(why) {
  const job = exitTail.then(async () => {
    const st = await state.getState();
    const got = await askExit();
    if (!got) {
      /* 2.6.1: попытка записывается и без ответа — иначе окно вечно показывало
         бы «Смотрим адрес…» и человек не знал бы, что служба молчит */
      await state.patchState({ exitAsk: Date.now() });
      console.log(`[pxs] выход (${why}): адрес не прочитан — прежний ответ остаётся`);
      return null;
    }
    const now = await state.getState();
    /* Пока шёл запрос, состояние могло смениться (человек выключил прокси или
       сменил его) — тогда ответ относится уже не к тому пути. Отвечаем только
       на тот же вопрос: включён тот же прокси или так же выключен. */
    if (now.enabled !== st.enabled || now.activeProxyId !== st.activeProxyId) {
      console.log(`[pxs] выход (${why}): состояние сменилось, пока шёл запрос — не записываю`);
      return null;
    }
    const nowAt = Date.now();
    const patch = { exitIp: got.ip, exitCc: got.cc, exitCity: got.city, exitAt: nowAt, exitAsk: nowAt, exitVia: now.enabled ? 'proxy' : 'direct' };
    if (!now.enabled) patch.directIp = got.ip;
    await state.patchState(patch);
    console.log(`[pxs] выход (${why}): сайты видят ${got.ip}${got.cc ? ' (' + got.cc + ')' : ''}${now.enabled ? '' : ' — прокси выключен'}`);
    return got;
  });
  exitTail = job.catch(() => {});
  return job;
}

async function startProbe(cmd) {
  const [settings, st] = await Promise.all([state.getSettings(), state.getState()]);

  // Прежний запрос в полёте больше ни о чём не говорит: прокси сменили командой окна.
  // Его исход отбрасывается (поколение сдвинуто), а пометка probing — либо снимается
  // здесь, либо ставится заново новым запросом.
  const stale = probing !== null && probing.doneAt === 0;
  if (stale) {
    probing.ctrl.abort();
    probeGen += 1;
  }

  if (settings.verify !== true || !st.enabled || !st.activeProxyId) {
    if (stale) await probeOff();
    return null;
  }

  const lists = pac.listsFrom(settings);   // тот же выбор режима, что у applyProxy
  const thirdOnly = !!(lists && lists.listMode === 'white');
  if (thirdOnly) console.log(`[pxs] проверка при подключении (${cmd}): белый список — только по чужим адресам связи`);

  const job = { id: st.activeProxyId, gen: ++probeGen, ctrl: new AbortController(), doneAt: 0, thirdOnly };
  probing = job;
  await state.patchState({ probing: true });
  return job;
}

async function finishProbe(job) {
  let res;
  try {
    res = await probe.probe(job.ctrl.signal, { thirdOnly: job.thirdOnly });
  } finally {
    if (probing && probing.gen === job.gen) probing.doneAt = Date.now();   // более новый запрос в полёте не трогаем
  }

  const now = await state.getState();
  if (probeGen !== job.gen || now.activeProxyId !== job.id) {   // был новый запрос проверки либо прокси сменён — не наш результат
    console.log('[pxs] проверка при подключении: прокси сменён, пока шёл запрос — результат не записан');
    if (probeGen === job.gen) await probeOff();   // прокси сменили не командой окна — новой пометки нет, снимаем свою
    return;
  }
  await probeResult(Date.now(), res.ok ? res.ms : 0, res.ok && res.siteDown);
  // Тишина на всех хостах (третья и пятая выдачи, В2-а) — прокси не отвечает: тот же путь, что при обрыве.
  if (res.ok) return;
  if (res.silent) {
    startDead('тишина на всех хостах при проверке при подключении', job.id);
    return;
  }
  /* 2.6: проверка не прошла, но хосты не молчали — значит, запросы упали на
     ошибках. Для записи с угаданным протоколом это первый подозреваемый:
     живой прокси на другой схеме отвечает именно так. Сначала лечение
     протокола, и только если оно ничего не нашло — честное «не отвечает»:
     «подключено» при полностью нерабочем канале — неправда, которую человек
     иначе видит только по пустым страницам. */
  const after = async () => {
    if (await healType(job.id, { fromProbe: true })) return;
    const [list, cur] = await Promise.all([state.getProxies(), state.getState()]);
    const p = list.find((x) => x && x.id === job.id);
    if (!p || p.typeGuess !== true || p.typeVerified === true) return;   // точный тип — прежние правила
    if (!cur.enabled || cur.activeProxyId !== job.id || cur.lastError !== null) return;
    startDead('проверка при подключении: ни один запрос не прошёл, протокол угадан', job.id);
  };
  (inQueue ? after() : inLine(after)).catch((err) => {
    console.error('[pxs] разбор непрошедшей проверки упал:', err);
  });
}

/*
 * Ошибки настоящего трафика. Слушатель на верхнем уровне, синхронный,
 * без extraInfoSpec (наблюдение, не блокировка), ничего не возвращает —
 * как наблюдатель onAuthRequired выше. Ответ на «выключен ли прокси» и
 * «не 'auth' ли уже» даёт чтение состояния, но только когда порог набран:
 * читать хранилище на каждую ошибку каждого запроса незачем.
 * 7В: свои запросы проверки (все пять) разбираются до тишины — отказ
 * соединения на любом из них означает 'dead' сразу (startDead с id
 * прокси, о котором запрос).
 */
chrome.webRequest.onErrorOccurred.addListener((details) => {
  // 7Ж: учёт запросов страницы — отдельной работой в try/catch ДО фильтра
  // обрыва, чтобы своя ошибка не задела детекцию мёртвого прокси (7Б).
  try { trackReq(details, null, details && details.error); } catch (err) { console.warn('[pxs] учёт запросов: ошибка запроса не учтена', err); }   // 7К.2 (А-6): учёт фон не роняет, но и не молчит
  if (!details || !isDeadError(details.error)) return;
  if (typeof navigator !== 'undefined' && navigator.onLine === false) return;   // В4: без сети падает всё, прокси ни при чём
  if (isProbeRequest(details)) {
    startDead('отказ соединения с прокси на запросе проверки при подключении', probing.id);
    return;
  }
  if (Date.now() < quietUntil) return;   // запоздавшие отказы прежнего прокси
  const host = requestHost(details.url);
  if (host) noteDeadError(host);
}, { urls: ['<all_urls>'] });

/* ── учёт запросов страницы (7Ж, 7.х; решение человека 18.09, ответ Т5–Т7) ──
 * Строка «Прокси для:» показывает счёт загрузки — сколько адресов (хостов),
 * к которым обращалась вкладка, ответило без ошибок; панель показывает эти
 * адреса и что с каждым случилось. Данные собирает фон: chrome.webRequest
 * приносит исход каждого запроса с его tabId, адресом и (при
 * проксировании) IP прокси. Живут во временной области хранилища (ключ
 * pageHosts, до закрытия браузера), читает их попап сам (storage.sessionGet,
 * как section) — команды фону нет.
 *
 * Всё это работает ТОЛЬКО при settings.siteTrack (по умолчанию выключен).
 * Слушатель завершённых запросов всё равно висит на верхнем уровне (иначе после сна
 * воркера страницы его не разбудят), но при выключенной настройке выходит
 * первой строкой по флагу из памяти воркера — БЕЗ чтения хранилища
 * (ответ Т6). Обработчик не делает ничего, кроме учёта, и не выпускает
 * наружу исключений (try/catch у слушателя): цена — воркер бодрствует при
 * загрузке страниц у всех, память в десятки МБ (проверка глазами —
 * диспетчер задач Chrome), — человек её принял.
 *
 * ⚠️ Память воркера — «допустимо» (мастер-промт 3.2):
 *  - trackOn — прочитанный флаг siteTrack; null, пока не прочитан при старте
 *    воркера; false — учёт выключен, событий не копим; true — считаем;
 *  - preBuffer — события до чтения флага (≤ BUFFER): терять main_frame
 *    нельзя, иначе прошлая страница не сбросится (ответ Т5(2)); после
 *    чтения флага буфер проигрывается по порядку либо выбрасывается;
 *  - store — карта pageHosts в памяти: читается из session один раз после
 *    пробуждения (ensureStore), пишется с задержкой PAGE_WRITE_MS (пачка
 *    событий — одна запись); потеря до PAGE_WRITE_MS событий при гашении
 *    воркера безвредна — счёт справочный;
 *  - activeIp — адрес активного прокси, если он IP-литерал (для via:
 *    details.ip === activeIp — запрос шёл через прокси); имя, а не IP —
 *    activeIp пуст, via не пишется (ответ Т5(3)).
 */
const PAGE_WRITE_MS = 500;
/* 7Л, шаг 3: списки последних запросов (reqs у адреса записи вкладки) пишутся только
   при квоте временной области ≥ PAGE_REQS.MIN_QUOTA — читается один раз при
   старте воркера через storage.sessionQuota() (7К.2, А-10: хранилище браузера
   только в storage.js); нет числа (старый Chrome, стенд) — не пишутся */
const sessionQuota = storage.sessionQuota();
const reqsOn = sessionQuota !== null && sessionQuota >= constants.PAGE_REQS.MIN_QUOTA;
let trackOn = null;
let preBuffer = [];
let store = null;
let storeLoading = null;
let storeDirty = false;
let storeTimer = null;
let activeIp = '';

/** Флаг siteTrack прочитан при старте воркера: включён — проиграть буфер, выключен — выбросить и стереть ключ. */
async function initTrack() {
  try {
    const settings = await state.getSettings();
    trackOn = settings.siteTrack === true;
    whiteMode = isWhite(settings);
  } catch (err) {
    trackOn = false;
    console.error('[pxs] учёт запросов: не удалось прочитать настройку:', err);
  }
  const buffered = preBuffer;
  preBuffer = [];
  if (trackOn) {
    for (const d of buffered) applyReq(d).catch((err) => { console.warn('[pxs] учёт запросов: событие из буфера не учтено', err); });   // 7К.2 (А-6)
  } else {
    await storage.sessionRemove(constants.SESSION_KEYS.PAGE_HOSTS).catch((err) => { console.warn('[pxs] учёт запросов: ключ pageHosts не стёрт', err); });   // 7К.2 (А-6)
  }
}

/** Действует ли белый список — для правила обрыва (7Ж): тот же listsFrom, что у applyProxy. */
function isWhite(settings) {
  const lists = pac.listsFrom(settings);
  return !!(lists && lists.listMode === 'white');
}

/** Адрес активного прокси в памяти (для via). Зовётся при старте и смене state. */
async function refreshActiveIp() {
  try {
    const st = await state.getState();
    if (!st.enabled || !st.activeProxyId) { activeIp = ''; return; }
    const found = (await state.getProxies()).find((p) => p && p.id === st.activeProxyId);
    activeIp = found && isIPHost(found.ip) ? found.ip : '';
  } catch (err) {
    activeIp = '';
  }
}

/** Карта pageHosts в память — один раз после пробуждения воркера. */
function ensureStore() {
  if (store) return Promise.resolve();
  if (!storeLoading) {
    storeLoading = storage.sessionGet(constants.SESSION_KEYS.PAGE_HOSTS).then((saved) => {
      if (!store) store = saved && typeof saved === 'object' ? saved : {};
    }).catch((err) => { if (!store) store = {}; console.warn('[pxs] учёт запросов: карта адресов не прочиталась', err); });   // 7К.2 (А-6)
  }
  return storeLoading;
}

/** Запись store в session пачкой — не на каждое событие. */
function scheduleWrite() {
  storeDirty = true;
  if (storeTimer) return;
  storeTimer = setTimeout(() => {
    storeTimer = null;
    if (!storeDirty) return;
    storeDirty = false;
    storage.sessionSet(constants.SESSION_KEYS.PAGE_HOSTS, store).catch((err) => {
      // 7Л, шаг 3: не влезло в квоту — списки запросов всех вкладок стираем,
      // счёт адресов остаётся, и пишем ещё раз; списки наберутся заново
      let had = false;
      for (const id of Object.keys(store)) {
        const hosts = store[id] && store[id].hosts;
        if (!hosts) continue;
        for (const k of Object.keys(hosts)) if (hosts[k] && hosts[k].reqs) { delete hosts[k].reqs; had = true; }
      }
      console.error('[pxs] учёт запросов: запись не удалась' + (had ? ' — списки запросов стёрты, счёт оставлен' : '') + ':', err);
      if (had) storage.sessionSet(constants.SESSION_KEYS.PAGE_HOSTS, store).catch((e2) => {
        console.error('[pxs] учёт запросов: повторная запись не удалась:', e2);
      });
    });
  }, PAGE_WRITE_MS);
}

/**
 * Точка входа из слушателей. Синхронная проверка флага (без хранилища),
 * дальше — асинхронный учёт. statusCode — от завершённого запроса (5xx = сбой),
 * error — из onErrorOccurred.
 */
function trackReq(details, statusCode, error) {
  if (trackOn === false) return;         // настройка выключена — ничего (Т6)
  if (!details || typeof details.tabId !== 'number' || details.tabId < 0) return;
  if (details.documentLifecycle && details.documentLifecycle !== 'active') return;   // предзагрузка — не то, что видит человек
  if (!requestHost(details.url)) return;
  const d = { tabId: details.tabId, url: details.url, type: details.type, ip: details.ip, statusCode, error, t: details.timeStamp };
  if (trackOn === null) {                // флаг ещё не прочитан — копим (Т5(2))
    // буфер полон — остальное теряем, но не main_frame: без него прошлая
    // страница вкладки не сбросится и счёт сложится с чужим
    if (preBuffer.length < constants.PAGE_HOSTS_LIMITS.BUFFER || d.type === 'main_frame') preBuffer.push(d);
    return;
  }
  applyReq(d).catch((err) => {
    console.error('[pxs] учёт запросов упал:', err);
  });
}

/**
 * Учесть один запрос в store. Классификация (ответы Т7):
 *  - PAGE_SKIP_ERRORS (страница сама отменила запрос) — не считаем вовсе;
 *  - PAGE_BLOCKED_ERRORS (блокировщик, политика) — адрес виден серой
 *    меткой, в счёт не входит (blocked:true, n не растёт);
 *  - PAGE_OK_ERRORS и ERR_CACHE_* — адрес ответил, сбоя нет;
 *  - HTTP ≥ 500 — сбой «HTTP nnn»; 4xx и меньше — ответил;
 *  - любая другая сетевая ошибка — сбой с её кодом.
 * main_frame — новая навигация: запись вкладки начинается заново, затем в
 * неё пишется сам главный документ (его сбой → «0 из 1»). Хост — как в
 * tabHost попапа: строчными, IPv6 без скобок.
 */
async function applyReq(d) {
  await ensureStore();
  const host = requestHost(d.url).toLowerCase().replace(/^\[(.*)\]$/, '$1');
  if (!host) return;
  const code = typeof d.error === 'string' ? d.error.replace(/^net::/, '') : null;
  if (code && constants.PAGE_SKIP_ERRORS.includes(code)) return;
  const okAnyway = code && (constants.PAGE_OK_ERRORS.includes(code) || code.startsWith(constants.PAGE_OK_ERROR_PREFIX));

  const fresh = d.type === 'main_frame';
  if (fresh) store[d.tabId] = { at: Date.now(), hosts: {} };
  let rec = store[d.tabId];
  if (!rec) rec = store[d.tabId] = { at: Date.now(), hosts: {} };
  rec.at = Date.now();

  let h = rec.hosts[host];
  if (!h) {
    if (Object.keys(rec.hosts).length >= constants.PAGE_HOSTS_LIMITS.HOSTS && !fresh) { scheduleWrite(); trimTabs(); return; }
    h = rec.hosts[host] = { n: 0, fail: 0, err: null, via: undefined, blocked: false };
  }

  if (code && constants.PAGE_BLOCKED_ERRORS.includes(code)) {
    h.blocked = true;                    // серая метка, в счёт не идёт
  } else {
    h.n += 1;
    const httpFail = typeof d.statusCode === 'number' && d.statusCode >= 500;
    if ((code && !okAnyway) || httpFail) { h.fail += 1; h.err = code || 'HTTP ' + d.statusCode; }
  }
  // via — по IP ответившего узла; пустой ip (запрос не дошёл до узла) —
  // маршрут неизвестен, не «напрямую» (уточнение 7Л, шаг 3)
  if (activeIp && typeof d.ip === 'string' && d.ip) h.via = d.ip === activeIp;
  if (reqsOn) noteReq(rec, h, d, code);

  trimTabs();
  scheduleWrite();
}

/**
 * 7Л, шаг 3: запись запроса в список адреса (hosts[host].reqs — форма
 * мастер-промта 3.5) — для страницы «Запросы адреса». Хранится коротко:
 * p — полный адрес запроса (схема, хост, путь, параметры; без фрагмента;
 * длиннее PAGE_REQS.MAX_LEN — обрезан; этап 9, правка человека 29.09),
 * t — тип запроса браузера (main_frame, script, image…), s — итог: код HTTP
 * (число) либо код ошибки браузера (строка), v — через прокси (true / false /
 * null — неизвестно), at — время события. Пределы PAGE_REQS: на адрес —
 * самый старый его запрос вытесняется, на вкладку — самый старый среди всех
 * адресов вкладки. Отменённые страницей (PAGE_SKIP_ERRORS) сюда не доходят —
 * applyReq вышел раньше; заблокированные пишутся с кодом — страница
 * показывает «заблокирован».
 */
function noteReq(rec, h, d, code) {
  if (!Array.isArray(h.reqs)) h.reqs = [];
  h.reqs.push({
    p: reqPath(d.url),
    t: typeof d.type === 'string' ? d.type : '',
    s: code || (typeof d.statusCode === 'number' ? d.statusCode : null),
    v: activeIp && typeof d.ip === 'string' && d.ip ? d.ip === activeIp : null,
    at: typeof d.t === 'number' ? Math.round(d.t) : Date.now(),
  });
  if (h.reqs.length > constants.PAGE_REQS.PER_HOST) h.reqs.shift();
  let total = 0, oldest = null;
  for (const k of Object.keys(rec.hosts)) {
    const r = rec.hosts[k].reqs;
    if (!Array.isArray(r) || !r.length) continue;
    total += r.length;
    if (!oldest || r[0].at < oldest[0].at) oldest = r;
  }
  if (total > constants.PAGE_REQS.PER_TAB && oldest) oldest.shift();
}

/**
 * Полный адрес запроса без #фрагмента: origin (схема://хост[:порт]) + путь +
 * параметры; длиннее PAGE_REQS.MAX_LEN — обрезан (MAX_LEN − 1 знак и «…»).
 * Учитываются только http(s) (requestHost), так что origin всегда
 * «схема://хост[:порт]». Этап 9 (правка человека 29.09): до него — только
 * путь с параметрами, до 160 знаков.
 */
function reqPath(url) {
  try {
    const u = new URL(url);
    const p = u.origin + u.pathname + u.search;
    const max = constants.PAGE_REQS.MAX_LEN;
    return p.length > max ? p.slice(0, max - 1) + '…' : p;
  } catch (err) {
    return '';
  }
}

/** Не держать больше TABS вкладок: лишние по времени последнего события. */
function trimTabs() {
  const ids = Object.keys(store);
  if (ids.length <= constants.PAGE_HOSTS_LIMITS.TABS) return;
  ids.sort((a, b) => (store[a].at || 0) - (store[b].at || 0));
  for (const id of ids.slice(0, ids.length - constants.PAGE_HOSTS_LIMITS.TABS)) delete store[id];
}

