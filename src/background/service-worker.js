let preparing = null;

/**
 * Подготовка хранилища. ОДНА В РАБОТЕ.
 *
 * При старте браузера её зовут и onStartup, и код в конце этого файла.
 * Повторный вызов присоединяется к уже идущей работе, а не запускает
 * вторую. С этапа 8 этим же путём идёт перенос данных прошлой версии
 * (runPrepare → migration.migrate() на исходе 'legacy'), и двух
 * параллельных переносов быть не должно — одно обещание это и даёт.
 */
function prepareStorage() {
  if (!preparing) {
    preparing = runPrepare()
      .then(async (prep) => {
        /* 2.3: одна точка нормализации формы данных — сразу после
           подготовки хранилища и до любой сверки. Идемпотентно: пишет
           только при реальном расхождении, поэтому на каждом старте
           воркера это чтение без записи. */
        if (prepared(prep)) {
          await normalizeTypes();
          await normalizeSettings();
        }
        return prep;
      })
      .catch((err) => {
        // Упало — отпускаем обещание, чтобы следующее событие попробовало снова.
        preparing = null;
        console.error('[pxs] подготовка хранилища не удалась:', err);
        return { result: 'failed', legacy: false, version: null };
      });
  }
  return preparing;
}

/**
 * Четыре исхода: 'ready' и 'marked' — от storage.init(); с этапа 8 —
 * 'migrated' (хранилище прошлой версии только что перенесено: версия и
 * данные записаны одной операцией, дальше как 'ready') и 'legacy' только
 * при неудаче переноса (не записано ничего, расширение работает как до
 * переноса — auth.js читает креды из ключа прошлой версии; повтор — при
 * следующем старте воркера: обещание остаётся с этим исходом до сна).
 * Триггер переноса — состояние хранилища, а не событие onInstalled:
 * обновление приходит само, событие обновления можно и пропустить, а
 * воркер будит первый же запрос через прокси. Строку неудачи печатает
 * сам перенос; здесь — без console.error и без броска.
 */
async function runPrepare() {
  const res = await storage.init();

  if (res.result === 'marked') {
    console.log(`[pxs] хранилище было пустым — размечено, версия схемы ${res.version}`);
  } else if (res.result === 'ready') {
    console.log(`[pxs] хранилище уже размечено, версия схемы ${res.version}`);
  } else if (res.result === 'legacy') {
    const m = await migration.migrate();
    if (m.ok) {
      console.log(`[pxs] хранилище прошлой версии перенесено — версия схемы ${constants.SCHEMA_VERSION}`);
      return { result: 'migrated', legacy: false, version: constants.SCHEMA_VERSION };
    }
    // Не ошибка воркера, а исход подготовки: спокойная строка, причина уже напечатана переносом.
    console.log('[pxs] данные прошлой версии найдены, перенос не выполнен — повтор при следующем старте');
  }

  return res;
}

/**
 * Хранилище готово к работе: размечено, было размечено или только что
 * перенесено (этап 8). 'legacy' (перенос не удался) и 'failed' — нет:
 * сверка, проверка при старте, аккаунт и файл сообщений на таком
 * хранилище не идут.
 *
 * @param {{result: string}} prep итог prepareStorage()
 */
function prepared(prep) {
  return prep.result === 'ready' || prep.result === 'marked' || prep.result === 'migrated';
}

/*
 * Очередь применений (решение этапа 5, 09.09). Одна цепочка обещаний, через
 * которую идут все пути к настройке прокси браузера: команды окон enable,
 * switch и disable, siteReload (7Л), обе горячие клавиши (7Д), повторное
 * применение по подписке на settings (reapplyLists), переключение при
 * обрыве failover (7Б) и самолечение heal (6.1); следующее ждёт конца
 * предыдущего.
 * Без неё «выключить» из окна во время повторного применения могло
 * завершиться раньше его set — у браузера прокси есть, у нас «выключено».
 * Цепочка живёт в памяти воркера и сон переживать не должна: после
 * пробуждения она пустая, это нормально — в ней только работа в полёте.
 * Упавшая работа очередь не заклинивает: ошибка возвращается тому, кто звал.
 */
let chain = Promise.resolve();
/* 2.6: идёт ли сейчас работа внутри очереди. Нужно одному месту — лечению
   протокола после обрыва (healType): его запускает и слушатель отказа
   соединения (вне очереди — значит через inLine), и переключение при
   обрыве (уже внутри очереди). Второй inLine изнутри был бы ожиданием
   самого себя — то есть вечным «Подключением» в окнах. */
let inQueue = false;

function inLine(work) {
  const turn = chain.then(() => {
    inQueue = true;
    const p = Promise.resolve().then(() => work());   // 7К.2 (А-5): работа без аргумента — итог предыдущей ей не передаётся
    return p.finally(() => { inQueue = false; });
  });
  chain = turn.catch(() => {});
  return turn;
}

