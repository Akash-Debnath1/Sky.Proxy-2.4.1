/* Список стран для выбора страны руками — теперь все коды спрайта.
   Рецептов в нём нет: второй элемент пары оставлен, чтобы не менять
   форму, которой пользуется gpRows и CC_MAP (проверка кода в setGeo).
   Сортируется по названию на языке браузера там же, в gpRows: алфавит
   не подсказывает ложную «важность» одних стран перед другими. */
/* коды наружу — заглавными, как в схеме PROXY (cc: len 2 в верхнем
   регистре): спрайт хранит имена файлов строчными, поэтому flag() и
   переводит код в нижний регистр сам, а COUNTRIES отдаёт привычный CC */
export const COUNTRIES = FLAG_CODES.map((cc) => [cc.toUpperCase(), '']);
export const CC_MAP = Object.fromEntries(COUNTRIES.map(c => [c[0], c]));

const FLAG_POS = Object.fromEntries(FLAG_CODES.map((cc, i) => [cc.toUpperCase(), i]));

/**
 * Флаг страны размером 17×12.
 * @param {string} cc код ISO 3166-1 alpha-2
 */
export function flag(cc){
  const i = FLAG_POS[String(cc || '').toUpperCase()];
  if(i === undefined) return FLAG_NONE;   /* 3Б.1: серый прямоугольник из icons.js */
  const x = -(i % FLAG_COLS) * 17;
  const y = -Math.floor(i / FLAG_COLS) * 12;
  return `<i class="fl" style="background-position:${x}px ${y}px" aria-hidden="true"></i>`;
}
