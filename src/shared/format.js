/* ── срок действия: считаем дни, показываем только когда пора ── */
export function expDays(p){
  /* 3Б.1: календарные дни от местной полуночи, а не 24-часовые отрезки от
     текущего момента. В прототипах стояло Math.ceil((p.exp - Date.now()) / 864e5):
     срок «сегодня в 23:00» днём показывался как «истекает завтра».
     Округление, а не деление: между двумя полуночами при переводе часов
     23 или 25 часов, и деление дало бы 0.96 или 1.04. */
  const today = new Date(); today.setHours(0, 0, 0, 0);
  const day = new Date(p.exp); day.setHours(0, 0, 0, 0);
  return Math.round((day - today) / 864e5);
}
/* В прототипах: L.expToday / L.expTomorrow / L.expInDays(d), где expInDays —
   функция словаря с plural(). В messages.json функций нет: число уходит в $1,
   форму слова выбирает msgN по правилам языка (expInDays_one/_few/_many/_other). */
export function expLabel(d){ return d <= 0 ? msg('expToday') : d === 1 ? msg('expTomorrow') : msgN('expInDays', d); }
export const expShort = d => d <= 0 ? msg('expShToday') : d === 1 ? msg('expShTomorrow') : msg('expShDays', [String(d)]);
export const isExpired = p => !!(p && p.exp && expDays(p) < 0);
/* Пороги остатка срока в календарных днях, одни на оба окна (3Б.6: до этого
   числа 7 и 2 стояли в шести местах двух скриптов; их же будут читать
   уведомления этапа 7).
   EXP_WARN_DAYS — с этого остатка срок показывается и подсвечивается
   янтарным: чип в герое и в строке списка на странице, значок часов в
   селекторе и строке попапа, уведомление «скоро истечёт», строка выбора
   по ключу. EXP_BAD_DAYS — с этого остатка он красный. Истёкший срок
   (дни < 0) — отдельная ветка, isExpired. */
export const EXP_WARN_DAYS = 7;
export const EXP_BAD_DAYS = 2;

/* ── названия стран: словарь называет, таблица флагов рисует ──
   В прототипе страницы: const geoName = cc => L.geo[cc] || cc;
   Таблица geo переехала в _locales как geo_XX, поэтому теперь она есть и у попапа.
   msgOpt, а не msg: код страны вне таблицы (например, UK из API) показывается
   как есть — это задуманный исход, а не потерянный ключ, предупреждать нечего. */
export const geoName = cc => msgOpt('geo_' + cc) || cc;

/* ── страна известна? ──
   Три пути, и все три законны: прокси пришёл по ключу API — страна
   приехала вместе с адресом; человек отметил её сам в списке на
   странице; 2.4 — фон определил её по адресу (geo.js) и поставил ccAuto.
   Раньше здесь было написано, что определить страну по IP расширение не
   может; в 2.4 это перестало быть правдой: запрос идёт к публичному
   геосервису за кодом страны, кешируется на 30 дней и отключается
   тумблером «Страна по IP». Пусто — флага нет, и это по-прежнему
   нормальное состояние, а не ошибка.
   3Б.6: одна проверка на оба окна; в попапе и на странице стояли две
   одинаковые копии. */
export const hasGeo = p => !!(p && p.cc);

/* ── место: страна и город ──
   2.4: город приходит от геосервиса вместе со страной и стоит вторым:
   «Philippines, Lahug». Города нет (сервис его не отдал или страну
   поставил человек) — остаётся одно название страны, без запятой. */
export function geoPlace(p){
  if (!p || !p.cc) return '';
  const city = typeof p.city === 'string' ? p.city.trim() : '';
  return city ? `${geoName(p.cc)}, ${city}` : geoName(p.cc);
}

/* ── строка, по которой ищем прокси ──
   Адрес, порт, логин, страна — и кодом, и названием на языке браузера, —
   заметки. Пароль намеренно не входит: искать по паролю незачем, а
   совпадение по нему выглядело бы так, будто мы его показываем.
   Окно само проверяет proxyHay(p).includes(q) со своим запросом,
   приведённым к нижнему регистру.
   3Б.6: одна на оба окна — в попапе (pmHay) и на странице (proxyHay)
   тела совпадали дословно. */
export function proxyHay(p){
  /* 2.1: тип и «socks»/«http» — тоже часть строки поиска: набрав «socks»,
     человек находит SOCKS-записи, не листая список. */
  const type = String(p.type || '');
  /* 2.4: и город — часть строки поиска: набрал «lahug» — нашёл строку */
  return [p.ip, p.port, p.login, type, type.toLowerCase(), p.cc || '', p.cc ? geoName(p.cc) : '', typeof p.city === 'string' ? p.city : '', ...(p.tags || [])].join(' ').toLowerCase();
}

