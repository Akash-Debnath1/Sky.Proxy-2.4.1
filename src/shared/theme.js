/* src/shared/theme.js — тема и язык окна до первой отрисовки; один скрипт
   на попап, страницу и с 7Л страницу запросов src/requests/ (ей попап даёт
   тот же параметр ?theme=light в адресе).
   Подключается обычным <script src> в <head>, синхронно и первым: окно
   попапа разбирается заново при каждом клике по значку, а popup.js —
   модуль, то есть отложенный. Поставь тему он — первый кадр ушёл бы в
   тёмной, следующий в светлой: вспышка. Скрипт в <head> видит только
   <html>, поэтому атрибут data-theme живёт на нём (решение 07.09), а не
   на .pop, как в прототипе; фон в цвет темы задан на html в popup.css.
   Импортов у классического скрипта нет, и общий слой сюда не подключить —
   это нормально: текстов здесь нет, в хранилище расширения он не ходит.

   Значения атрибута — как в прототипе: 'light' для светлой темы, для
   тёмной атрибута нет (CSS различает html[data-theme="light"] и
   html:not([data-theme="light"])).

   Этап 4 (решение 08.09): сохранённую тему синхронный скрипт узнаёт из
   АДРЕСА окна — параметра ?theme=light. Хранилище расширения читается
   только асинхронно, а веб-хранилище страницы мастер-промт запрещает.
   Попапу параметр подставляет фон: при каждом старте воркера и при каждой
   смене settings.theme он зовёт chrome.action.setPopup с адресом
   popup.html?theme=light (светлая) или popup.html (тёмная). Странице тот
   же параметр даёт попап, когда открывает её сам; из chrome://extensions
   страница открывается без параметра, и один тёмный кадр при светлой теме
   принят: это обычная вкладка, вспышка там не та, что у попапа. Дальше
   тему держит скрипт окна по settings.theme из хранилища. */
function applyTheme(theme){
  if(theme === 'light') document.documentElement.dataset.theme = 'light';
  else delete document.documentElement.dataset.theme;
}
applyTheme(new URLSearchParams(location.search).get('theme') === 'light' ? 'light' : 'dark');

/* lang в разметку не зашит (чек-лист 3Б.2): язык интерфейса берётся у
   браузера, тот же, по которому chrome.i18n выбирает messages.json.
   Ставится здесь, до разбора текстов в теле страницы: от атрибута
   зависят переносы, экранные дикторы и предложение перевести страницу.
   3Б.6: это единственное место, где ставится lang, — строка прототипа в
   applyStatic() обоих окон, повторявшая то же значение, снята. */
document.documentElement.lang = chrome.i18n.getUILanguage();
